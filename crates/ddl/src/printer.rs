//! Canonical DDL printing in the official emulator's GetDatabaseDdl format.

use crate::parser::{join_idents, quote_path, quote_string};
use crate::schema::*;

pub(crate) fn type_sql(ty: &ColumnType) -> String {
    match ty {
        ColumnType::Bool => "BOOL".into(),
        ColumnType::Int64 => "INT64".into(),
        ColumnType::Float32 => "FLOAT32".into(),
        ColumnType::Float64 => "FLOAT64".into(),
        ColumnType::Numeric => "NUMERIC".into(),
        ColumnType::String(n) => format!("STRING({})", len(*n)),
        ColumnType::Bytes(n) => format!("BYTES({})", len(*n)),
        ColumnType::Date => "DATE".into(),
        ColumnType::Timestamp => "TIMESTAMP".into(),
        ColumnType::Json => "JSON".into(),
        ColumnType::Interval => "INTERVAL".into(),
        ColumnType::Uuid => "UUID".into(),
        ColumnType::TokenList => "TOKENLIST".into(),
        ColumnType::Array(t) => format!("ARRAY<{}>", type_sql(t)),
        ColumnType::Struct(fields) => {
            let f: Vec<String> = fields
                .iter()
                .map(|(n, t)| match n {
                    Some(n) => format!("{} {}", crate::parser::quote_ident(n), type_sql(t)),
                    None => type_sql(t),
                })
                .collect();
            format!("STRUCT<{}>", f.join(", "))
        }
    }
}

fn len(n: Option<u64>) -> String {
    n.map_or("MAX".to_string(), |n| n.to_string())
}

fn key_sql(parts: &[KeyPart]) -> String {
    parts
        .iter()
        .map(|k| match k.order {
            SortOrder::Asc => crate::parser::quote_ident(&k.column),
            SortOrder::Desc => format!("{} DESC", crate::parser::quote_ident(&k.column)),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

pub(crate) fn column_sql(c: &Column) -> String {
    let mut s = format!(
        "{} {}",
        crate::parser::quote_ident(&c.name),
        type_sql(&c.ty)
    );
    if let Some(n) = c.vector_length {
        s.push_str(&format!("(vector_length=>{n})"));
    }
    if c.not_null {
        s.push_str(" NOT NULL");
    }
    if let Some(d) = &c.default {
        s.push_str(&format!(" DEFAULT ({d})"));
    }
    if let Some(e) = &c.on_update {
        s.push_str(&format!(" ON UPDATE ({e})"));
    }
    match &c.generated {
        Some(Generated::Expr { expr, stored }) => {
            s.push_str(&format!(" AS ({expr})"));
            if *stored {
                s.push_str(" STORED");
            }
        }
        Some(Generated::Identity { options }) => {
            s.push_str(" GENERATED BY DEFAULT AS IDENTITY");
            if let Some(o) = options {
                s.push_str(&format!(" ({o})"));
            }
        }
        None => {}
    }
    if c.hidden {
        s.push_str(" HIDDEN");
    }
    let mut opts = Vec::new();
    if let Some(g) = &c.locality_group {
        opts.push(format!("    locality_group = {}", quote_string(g)));
    }
    if c.allow_commit_timestamp {
        opts.push("    allow_commit_timestamp = true".to_string());
    }
    if !opts.is_empty() {
        s.push_str(&format!(" OPTIONS (\n{}\n  )", opts.join(",\n")));
    }
    s
}

/// A table's or index's `OPTIONS (locality_group = ...)` clause, as production prints it.
fn locality_clause(g: &Option<String>) -> String {
    match g {
        Some(g) => format!(" OPTIONS (\n  locality_group = {}\n)", quote_string(g)),
        None => String::new(),
    }
}

/// `CREATE LOCALITY GROUP` as production prints it; the altered `default` group is an ALTER.
pub(crate) fn locality_group_sql(g: &LocalityGroup) -> String {
    let opts: Vec<String> = g
        .options
        .iter()
        .filter(|(_, v)| v != "NULL")
        .map(|(k, v)| format!("  {k} = {v}"))
        .collect();
    let name = crate::parser::quote_ident(&g.name);
    let is_default = g.name.eq_ignore_ascii_case(DEFAULT_LOCALITY_GROUP);
    let mut s = if is_default {
        format!("ALTER LOCALITY GROUP {name} SET")
    } else {
        format!("CREATE LOCALITY GROUP {name}")
    };
    if !opts.is_empty() {
        s.push_str(&format!(" OPTIONS (\n{}\n)", opts.join(",\n")));
    } else if is_default {
        s.push_str(" OPTIONS ()");
    }
    s
}

/// `CREATE LOCALITY GROUP` as the emulator prints it: options on one line, NULLs left out.
fn locality_group_sql_emulator(g: &LocalityGroup) -> String {
    let mut s = format!(
        "CREATE LOCALITY GROUP {}",
        crate::parser::quote_ident(&g.name)
    );
    if !g.options.is_empty() {
        let opts: Vec<String> = g
            .options
            .iter()
            .filter(|(_, v)| v != "NULL")
            .map(|(k, v)| format!("{k} = {v}"))
            .collect();
        s.push_str(&format!(" OPTIONS ( {} )", opts.join(", ")));
    }
    s
}

fn on_delete_sql(o: &OnDelete) -> &'static str {
    match o {
        OnDelete::Cascade => "ON DELETE CASCADE",
        OnDelete::NoAction => "ON DELETE NO ACTION",
    }
}

pub(crate) fn fk_sql(fk: &ForeignKey) -> String {
    let mut s = String::new();
    if !fk.generated_name {
        s.push_str(&format!(
            "CONSTRAINT {} ",
            crate::parser::quote_ident(&fk.name)
        ));
    }
    s.push_str(&format!(
        "FOREIGN KEY({}) REFERENCES {}({})",
        join_idents(&fk.columns),
        quote_path(&fk.ref_table),
        join_idents(&fk.ref_columns)
    ));
    if fk.on_delete_explicit || fk.on_delete == OnDelete::Cascade {
        s.push(' ');
        s.push_str(on_delete_sql(&fk.on_delete));
    }
    if !fk.enforced {
        s.push_str(" NOT ENFORCED");
    }
    s
}

pub(crate) fn check_sql(c: &CheckConstraint) -> String {
    if c.generated_name {
        format!("CHECK({})", c.expr)
    } else {
        format!(
            "CONSTRAINT {} CHECK({})",
            crate::parser::quote_ident(&c.name),
            c.expr
        )
    }
}

pub(crate) fn rdp_sql(r: &RowDeletionPolicy) -> String {
    format!(
        "ROW DELETION POLICY (OLDER_THAN({}, INTERVAL {} DAY))",
        crate::parser::quote_ident(&r.column),
        r.days
    )
}

pub(crate) fn table_sql(t: &Table) -> String {
    let mut s = format!("CREATE TABLE {} (\n", quote_path(&t.name));
    for c in &t.columns {
        s.push_str(&format!("  {},\n", column_sql(c)));
    }
    for fk in &t.foreign_keys {
        s.push_str(&format!("  {},\n", fk_sql(fk)));
    }
    for c in &t.checks {
        s.push_str(&format!("  {},\n", check_sql(c)));
    }
    if let Some(syn) = &t.synonym {
        s.push_str(&format!("  SYNONYM({}),\n", quote_path(syn)));
    }
    s.push_str(&format!(") PRIMARY KEY({})", key_sql(&t.primary_key)));
    if let Some(il) = &t.interleave {
        s.push_str(",\n  INTERLEAVE IN ");
        if il.in_parent {
            s.push_str(&format!(
                "PARENT {} {}",
                quote_path(&il.parent),
                on_delete_sql(&il.on_delete)
            ));
        } else {
            s.push_str(&quote_path(&il.parent));
        }
    }
    if let Some(r) = &t.row_deletion_policy {
        s.push_str(", ");
        s.push_str(&rdp_sql(r));
    }
    if t.locality_group.is_some() {
        s.push(',');
        s.push_str(&locality_clause(&t.locality_group));
    }
    s
}

pub(crate) fn index_sql(i: &Index) -> String {
    let mut s = String::from("CREATE ");
    if i.unique {
        s.push_str("UNIQUE ");
    }
    if i.null_filtered {
        s.push_str("NULL_FILTERED ");
    }
    s.push_str(&format!(
        "INDEX {} ON {}({})",
        quote_path(&i.name),
        quote_path(&i.table),
        key_sql(&i.key)
    ));
    if !i.storing.is_empty() {
        s.push_str(&format!(" STORING ({})", join_idents(&i.storing)));
    }
    if let Some(f) = &i.filter {
        s.push_str(&format!(" WHERE {f}"));
    }
    if let Some(p) = &i.interleave_in {
        s.push_str(&format!(", INTERLEAVE IN {}", quote_path(p)));
    }
    s.push_str(&locality_clause(&i.locality_group));
    s
}

pub(crate) fn search_index_sql(i: &SearchIndex) -> String {
    let mut s = format!(
        "CREATE SEARCH INDEX {} ON {}({})",
        quote_path(&i.name),
        quote_path(&i.table),
        join_idents(&i.columns)
    );
    if !i.storing.is_empty() {
        s.push_str(&format!(" STORING ({})", join_idents(&i.storing)));
    }
    if !i.partition_by.is_empty() {
        s.push_str(&format!(" PARTITION BY {}", join_idents(&i.partition_by)));
    }
    if !i.order_by.is_empty() {
        s.push_str(&format!(" ORDER BY {}", key_sql(&i.order_by)));
    }
    if let Some(f) = &i.filter {
        s.push_str(&format!(" WHERE {f}"));
    }
    if let Some(p) = &i.interleave_in {
        s.push_str(&format!(", INTERLEAVE IN {}", quote_path(p)));
    }
    if !i.options.is_empty() {
        s.push_str(&format!(" OPTIONS ({})", options_inline(&i.options)));
    }
    s
}

fn options_inline(opts: &[(String, String)]) -> String {
    opts.iter()
        .map(|(k, v)| format!("{k} = {v}"))
        .collect::<Vec<_>>()
        .join(", ")
}

const SEQUENCE_OPTION_ORDER: &[&str] = &[
    "sequence_kind",
    "skip_range_min",
    "skip_range_max",
    "start_with_counter",
];

pub(crate) fn sequence_sql(seq: &Sequence) -> String {
    let mut s = format!("CREATE SEQUENCE {}", quote_path(&seq.name));
    if seq.options.is_empty() {
        return s;
    }
    let mut opts: Vec<&(String, String)> = seq.options.iter().collect();
    opts.sort_by_key(|(k, _)| {
        SEQUENCE_OPTION_ORDER
            .iter()
            .position(|o| o.eq_ignore_ascii_case(k))
            .unwrap_or(usize::MAX)
    });
    let body: Vec<String> = opts.iter().map(|(k, v)| format!("  {k} = {v}")).collect();
    s.push_str(&format!(" OPTIONS (\n{})", body.join(",\n")));
    s
}

pub(crate) fn view_sql(v: &View) -> String {
    format!(
        "CREATE VIEW {} SQL SECURITY {} AS {}",
        quote_path(&v.name),
        if v.sql_security_invoker {
            "INVOKER"
        } else {
            "DEFINER"
        },
        v.sql
    )
}

impl Schema {
    /// Canonical statements as production's GetDatabaseDdl returns them. Snapshots store these,
    /// so they keep everything the schema holds.
    pub fn to_ddl(&self) -> Vec<String> {
        let mut out = Vec::new();
        self.database_options_ddl(&mut out);
        out.extend(self.locality_groups.iter().map(locality_group_sql));
        self.objects_ddl(&mut out);
        out
    }

    /// GetDatabaseDdl as the emulator returns it (`--emulator-compat`): locality groups come last
    /// and tables, columns and indexes don't print their `locality_group`.
    pub fn to_ddl_emulator_compat(&self) -> Vec<String> {
        let mut s = self.clone();
        for t in s.tables.values_mut() {
            t.locality_group = None;
            for c in &mut t.columns {
                c.locality_group = None;
            }
        }
        for i in s.indexes.values_mut() {
            i.locality_group = None;
        }
        let mut out = Vec::new();
        s.database_options_ddl(&mut out);
        s.objects_ddl(&mut out);
        out.extend(s.locality_groups.iter().map(locality_group_sql_emulator));
        out
    }

    fn database_options_ddl(&self, out: &mut Vec<String>) {
        if !self.options.is_empty() {
            let name = self.database_name.as_deref().unwrap_or("db");
            out.push(format!(
                "ALTER DATABASE {} SET OPTIONS ({})",
                crate::parser::quote_ident(name),
                options_inline(&self.options)
            ));
        }
    }

    fn objects_ddl(&self, out: &mut Vec<String>) {
        let ordered = |kind: ObjectKind| {
            self.creation_order
                .iter()
                .filter(move |(k, _)| *k == kind)
                .map(|(_, n)| n.as_str())
        };
        for key in ordered(ObjectKind::Schema) {
            if let Some(name) = self.schemas.get(key) {
                out.push(format!(
                    "CREATE SCHEMA {}",
                    crate::parser::quote_ident(name)
                ));
            }
        }
        for key in ordered(ObjectKind::Sequence) {
            if let Some(seq) = self.sequences.get(key) {
                out.push(sequence_sql(seq));
            }
        }
        for key in ordered(ObjectKind::Table) {
            let Some(t) = self.tables.get(key) else {
                continue;
            };
            out.push(table_sql(t));
            let mut idx: Vec<(&str, String)> = self
                .indexes
                .values()
                .filter(|i| i.table.eq_ignore_ascii_case(&t.name))
                .map(|i| (i.name.as_str(), index_sql(i)))
                .chain(
                    self.search_indexes
                        .values()
                        .filter(|i| i.table.eq_ignore_ascii_case(&t.name))
                        .map(|i| (i.name.as_str(), search_index_sql(i))),
                )
                .collect();
            idx.sort_by(|a, b| a.0.cmp(b.0));
            out.extend(idx.into_iter().map(|(_, s)| s));
        }
        let opaque = |kind: &'static str| {
            self.opaque
                .iter()
                .filter(move |o| o.kind == kind)
                .map(|o| o.ddl.clone())
        };
        out.extend(opaque("CHANGE STREAM"));
        out.extend(opaque("MODEL"));
        for key in ordered(ObjectKind::View) {
            if let Some(v) = self.views.get(key) {
                out.push(view_sql(v));
            }
        }
        out.extend(opaque("PROPERTY GRAPH"));
    }
}

fn if_exists(b: bool) -> &'static str {
    if b { "IF EXISTS " } else { "" }
}

fn if_not_exists(b: bool) -> &'static str {
    if b { "IF NOT EXISTS " } else { "" }
}

fn options_paren(opts: &[(String, String)]) -> String {
    format!("OPTIONS ({})", options_inline(opts))
}

fn locality_value(g: &Option<String>) -> String {
    g.as_deref().map_or("NULL".to_string(), quote_string)
}

fn alter_table_sql(table: &str, action: &AlterTable) -> String {
    let t = quote_path(table);
    let q = crate::parser::quote_ident;
    let body = match action {
        AlterTable::AddColumn {
            column,
            if_not_exists: ine,
        } => format!("ADD COLUMN {}{}", if_not_exists(*ine), column_sql(column)),
        AlterTable::DropColumn { name } => format!("DROP COLUMN {}", q(name)),
        AlterTable::AlterColumn { column } => format!("ALTER COLUMN {}", column_sql(column)),
        AlterTable::SetColumnDefault { name, default } => match default {
            Some(d) => format!("ALTER COLUMN {} SET DEFAULT ({d})", q(name)),
            None => format!("ALTER COLUMN {} DROP DEFAULT", q(name)),
        },
        AlterTable::SetColumnOnUpdate { name, on_update } => match on_update {
            Some(e) => format!("ALTER COLUMN {} SET ON UPDATE ({e})", q(name)),
            None => format!("ALTER COLUMN {} DROP ON UPDATE", q(name)),
        },
        AlterTable::SetColumnOptions {
            name,
            allow_commit_timestamp,
            locality_group,
        } => {
            let mut opts = Vec::new();
            if let Some(v) = allow_commit_timestamp {
                opts.push(format!("allow_commit_timestamp = {v}"));
            }
            if let Some(g) = locality_group {
                opts.push(format!("locality_group = {}", locality_value(g)));
            }
            format!("ALTER COLUMN {} SET OPTIONS ({})", q(name), opts.join(", "))
        }
        AlterTable::SetOptions { locality_group } => format!(
            "SET OPTIONS (locality_group = {})",
            locality_value(locality_group)
        ),
        AlterTable::AddForeignKey(fk) => format!("ADD {}", fk_sql(fk)),
        AlterTable::AddCheck(c) => format!("ADD {}", check_sql(c)),
        AlterTable::DropConstraint { name } => format!("DROP CONSTRAINT {}", q(name)),
        AlterTable::SetOnDelete(o) => format!("SET {}", on_delete_sql(o)),
        AlterTable::AddRowDeletionPolicy(r) => format!("ADD {}", rdp_sql(r)),
        AlterTable::ReplaceRowDeletionPolicy(r) => format!("REPLACE {}", rdp_sql(r)),
        AlterTable::DropRowDeletionPolicy => "DROP ROW DELETION POLICY".to_string(),
        AlterTable::AddSynonym(s) => format!("ADD SYNONYM {}", quote_path(s)),
        AlterTable::DropSynonym(s) => format!("DROP SYNONYM {}", quote_path(s)),
        AlterTable::Rename { to } => format!("RENAME TO {}", quote_path(to)),
        AlterTable::RenameWithSynonym { to, synonym } => format!(
            "RENAME TO {}, ADD SYNONYM {}",
            quote_path(to),
            quote_path(synonym)
        ),
    };
    format!("ALTER TABLE {t} {body}")
}

/// Canonical text of one statement. `CREATE` statements print exactly as in `Schema::to_ddl`.
pub fn print_statement(stmt: &Statement) -> String {
    match stmt {
        Statement::CreateSchema {
            name,
            if_not_exists: ine,
        } => format!(
            "CREATE SCHEMA {}{}",
            if_not_exists(*ine),
            crate::parser::quote_ident(name)
        ),
        Statement::DropSchema { name } => {
            format!("DROP SCHEMA {}", crate::parser::quote_ident(name))
        }
        Statement::CreateTable {
            table,
            if_not_exists: ine,
        } => {
            let s = table_sql(table);
            if *ine {
                s.replacen("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
            } else {
                s
            }
        }
        Statement::DropTable {
            name,
            if_exists: ie,
        } => {
            format!("DROP TABLE {}{}", if_exists(*ie), quote_path(name))
        }
        Statement::AlterTable {
            table,
            action,
            if_exists: ie,
        } => {
            let s = alter_table_sql(table, action);
            if *ie {
                s.replacen("ALTER TABLE ", "ALTER TABLE IF EXISTS ", 1)
            } else {
                s
            }
        }
        Statement::RenameTables { renames } => {
            let parts: Vec<String> = renames
                .iter()
                .map(|(a, b)| format!("{} TO {}", quote_path(a), quote_path(b)))
                .collect();
            format!("RENAME TABLE {}", parts.join(", "))
        }
        Statement::CreateIndex {
            index,
            if_not_exists: ine,
        } => {
            let s = index_sql(index);
            if *ine {
                s.replacen("INDEX ", "INDEX IF NOT EXISTS ", 1)
            } else {
                s
            }
        }
        Statement::DropIndex {
            name,
            if_exists: ie,
        } => {
            format!("DROP INDEX {}{}", if_exists(*ie), quote_path(name))
        }
        Statement::AlterIndex { name, action } => match action {
            AlterIndex::AddStoredColumn(c) => format!(
                "ALTER INDEX {} ADD STORED COLUMN {}",
                quote_path(name),
                crate::parser::quote_ident(c)
            ),
            AlterIndex::DropStoredColumn(c) => format!(
                "ALTER INDEX {} DROP STORED COLUMN {}",
                quote_path(name),
                crate::parser::quote_ident(c)
            ),
        },
        Statement::CreateSearchIndex { index } => search_index_sql(index),
        Statement::CreateLocalityGroup {
            group,
            if_not_exists: ine,
        } => {
            let mut s = format!(
                "CREATE LOCALITY GROUP {}{}",
                if_not_exists(*ine),
                crate::parser::quote_ident(&group.name)
            );
            if !group.options.is_empty() {
                s.push(' ');
                s.push_str(&options_paren(&group.options));
            }
            s
        }
        Statement::AlterLocalityGroup { name, options } => format!(
            "ALTER LOCALITY GROUP {} SET {}",
            crate::parser::quote_ident(name),
            options_paren(options)
        ),
        Statement::DropLocalityGroup {
            name,
            if_exists: ie,
        } => format!(
            "DROP LOCALITY GROUP {}{}",
            if_exists(*ie),
            crate::parser::quote_ident(name)
        ),
        Statement::AlterSearchIndex { name, action } => {
            let (verb, c) = match action {
                AlterSearchIndex::AddColumn(c) => ("ADD COLUMN", c),
                AlterSearchIndex::DropColumn(c) => ("DROP COLUMN", c),
                AlterSearchIndex::AddStoredColumn(c) => ("ADD STORED COLUMN", c),
                AlterSearchIndex::DropStoredColumn(c) => ("DROP STORED COLUMN", c),
            };
            format!(
                "ALTER SEARCH INDEX {} {verb} {}",
                quote_path(name),
                crate::parser::quote_ident(c)
            )
        }
        Statement::DropSearchIndex {
            name,
            if_exists: ie,
        } => {
            format!("DROP SEARCH INDEX {}{}", if_exists(*ie), quote_path(name))
        }
        Statement::CreateSequence {
            sequence,
            if_not_exists: ine,
        } => {
            let s = sequence_sql(sequence);
            if *ine {
                s.replacen("SEQUENCE ", "SEQUENCE IF NOT EXISTS ", 1)
            } else {
                s
            }
        }
        Statement::AlterSequence { name, options } => format!(
            "ALTER SEQUENCE {} SET {}",
            quote_path(name),
            options_paren(options)
        ),
        Statement::DropSequence {
            name,
            if_exists: ie,
        } => {
            format!("DROP SEQUENCE {}{}", if_exists(*ie), quote_path(name))
        }
        Statement::CreateView { view, or_replace } => {
            let s = view_sql(view);
            if *or_replace {
                s.replacen("CREATE ", "CREATE OR REPLACE ", 1)
            } else {
                s
            }
        }
        Statement::DropView {
            name,
            if_exists: ie,
        } => {
            format!("DROP VIEW {}{}", if_exists(*ie), quote_path(name))
        }
        Statement::AlterDatabase { options, name } => format!(
            "ALTER DATABASE {} SET {}",
            crate::parser::quote_ident(name),
            options_paren(options)
        ),
        Statement::Opaque { object, drop } => {
            if *drop {
                format!(
                    "DROP {} {}{}",
                    object.kind,
                    if object.ddl == "IF EXISTS" {
                        "IF EXISTS "
                    } else {
                        ""
                    },
                    quote_path(&object.name)
                )
            } else {
                object.ddl.clone()
            }
        }
    }
}
