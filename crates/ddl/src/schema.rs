use std::collections::BTreeMap;

/// Column type in the schema.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum ColumnType {
    Bool,
    Int64,
    Float32,
    Float64,
    Numeric,
    /// `None` = MAX.
    String(Option<u64>),
    Bytes(Option<u64>),
    Date,
    Timestamp,
    Json,
    Interval,
    Uuid,
    TokenList,
    Array(Box<ColumnType>),
    /// Only appears inside queries and ARRAY<STRUCT<...>> columns' expressions.
    Struct(Vec<(Option<String>, ColumnType)>),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SortOrder {
    Asc,
    Desc,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KeyPart {
    pub column: String,
    pub order: SortOrder,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Generated {
    /// `AS (expr) STORED` or virtual `AS (expr)`; `expr` is the SQL text.
    Expr { expr: String, stored: bool },
    /// `GENERATED BY DEFAULT AS IDENTITY (options)`; `options` is the text inside the parentheses.
    Identity { options: Option<String> },
}

impl Generated {
    /// The expression of an `AS (expr)` column.
    pub fn expr(&self) -> Option<(&str, bool)> {
        match self {
            Generated::Expr { expr, stored } => Some((expr, *stored)),
            Generated::Identity { .. } => None,
        }
    }
}

/// Whether a DEFAULT or ON UPDATE expression is `PENDING_COMMIT_TIMESTAMP()` (any case or spacing).
pub fn is_pending_commit_timestamp(expr: &str) -> bool {
    let e: String = expr.split_whitespace().collect();
    e.eq_ignore_ascii_case("PENDING_COMMIT_TIMESTAMP()")
}

/// The hidden key column the emulator adds to tables declared without a primary key.
pub const ROWID_COLUMN: &str = "rowid";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Column {
    pub name: String,
    pub ty: ColumnType,
    pub not_null: bool,
    /// `DEFAULT (expr)` SQL text.
    pub default: Option<String>,
    /// `ON UPDATE (expr)` SQL text; only `PENDING_COMMIT_TIMESTAMP()` is accepted.
    pub on_update: Option<String>,
    pub generated: Option<Generated>,
    pub allow_commit_timestamp: bool,
    /// Hidden columns (e.g. TOKENLIST ... HIDDEN) are excluded from SELECT *.
    pub hidden: bool,
    /// `ARRAY<FLOAT32|FLOAT64>(vector_length=>n)`.
    pub vector_length: Option<u64>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum OnDelete {
    Cascade,
    NoAction,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Interleave {
    pub parent: String,
    pub on_delete: OnDelete,
    /// `INTERLEAVE IN` (no PARENT): no parent-row existence requirement.
    pub in_parent: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForeignKey {
    pub name: String,
    pub columns: Vec<String>,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
    pub on_delete: OnDelete,
    /// `NOT ENFORCED` foreign keys are informational.
    pub enforced: bool,
    /// Declared without `CONSTRAINT name`: `name` is generated when the statement is applied
    /// (empty until then) and is not printed.
    pub generated_name: bool,
    /// `ON DELETE` was written out (GetDatabaseDdl prints it only then).
    pub on_delete_explicit: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CheckConstraint {
    pub name: String,
    /// SQL text of the boolean expression.
    pub expr: String,
    /// Declared without `CONSTRAINT name`: `name` is generated when the statement is applied
    /// (empty until then) and is not printed.
    pub generated_name: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RowDeletionPolicy {
    pub column: String,
    pub days: u64,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Table {
    /// Fully qualified (`schema.table` for named schemas).
    pub name: String,
    pub columns: Vec<Column>,
    pub primary_key: Vec<KeyPart>,
    pub interleave: Option<Interleave>,
    pub foreign_keys: Vec<ForeignKey>,
    pub checks: Vec<CheckConstraint>,
    pub row_deletion_policy: Option<RowDeletionPolicy>,
    pub synonym: Option<String>,
}

impl Table {
    pub fn column(&self, name: &str) -> Option<&Column> {
        self.columns
            .iter()
            .find(|c| c.name.eq_ignore_ascii_case(name))
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Index {
    pub name: String,
    pub table: String,
    pub key: Vec<KeyPart>,
    pub storing: Vec<String>,
    pub unique: bool,
    pub null_filtered: bool,
    pub interleave_in: Option<String>,
    /// `WHERE ...` filter SQL text.
    pub filter: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SearchIndex {
    pub name: String,
    pub table: String,
    pub columns: Vec<String>,
    pub storing: Vec<String>,
    pub partition_by: Vec<String>,
    pub order_by: Vec<KeyPart>,
    /// Option values are SQL literal text (`'1d'`, `true`, `5`).
    pub options: Vec<(String, String)>,
    /// `WHERE ...` filter SQL text.
    pub filter: Option<String>,
    pub interleave_in: Option<String>,
}

/// Objects we accept and store but do not execute (change streams, roles, grants, graphs, ...).
/// Kept verbatim so GetDatabaseDdl can return them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OpaqueObject {
    pub kind: String,
    pub name: String,
    pub ddl: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Sequence {
    pub name: String,
    pub options: Vec<(String, String)>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct View {
    pub name: String,
    pub sql: String,
    pub sql_security_invoker: bool,
}

/// One parsed DDL statement.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Statement {
    CreateSchema {
        name: String,
        if_not_exists: bool,
    },
    DropSchema {
        name: String,
    },
    CreateTable {
        table: Table,
        if_not_exists: bool,
    },
    DropTable {
        name: String,
        if_exists: bool,
    },
    AlterTable {
        table: String,
        action: AlterTable,
    },
    CreateIndex {
        index: Index,
        if_not_exists: bool,
    },
    DropIndex {
        name: String,
        if_exists: bool,
    },
    AlterIndex {
        name: String,
        action: AlterIndex,
    },
    CreateSearchIndex {
        index: SearchIndex,
    },
    DropSearchIndex {
        name: String,
        if_exists: bool,
    },
    CreateSequence {
        sequence: Sequence,
        if_not_exists: bool,
    },
    DropSequence {
        name: String,
        if_exists: bool,
    },
    CreateView {
        view: View,
        or_replace: bool,
    },
    DropView {
        name: String,
        if_exists: bool,
    },
    /// Option values are SQL literal text.
    AlterDatabase {
        options: Vec<(String, String)>,
        name: String,
    },
    AlterSequence {
        name: String,
        options: Vec<(String, String)>,
    },
    /// `RENAME TABLE a TO b, c TO d` (a single pair is `AlterTable` with `Rename`).
    RenameTables {
        renames: Vec<(String, String)>,
    },
    /// CHANGE STREAM, ROLE, GRANT, REVOKE, PROPERTY GRAPH, MODEL, ...
    Opaque {
        object: OpaqueObject,
        drop: bool,
    },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AlterTable {
    AddColumn {
        column: Column,
        if_not_exists: bool,
    },
    DropColumn {
        name: String,
    },
    AlterColumn {
        column: Column,
    },
    SetColumnDefault {
        name: String,
        default: Option<String>,
    },
    /// `ALTER COLUMN c SET ON UPDATE (expr)` / `DROP ON UPDATE`.
    SetColumnOnUpdate {
        name: String,
        on_update: Option<String>,
    },
    SetColumnOptions {
        name: String,
        allow_commit_timestamp: Option<bool>,
    },
    AddForeignKey(ForeignKey),
    AddCheck(CheckConstraint),
    DropConstraint {
        name: String,
    },
    SetOnDelete(OnDelete),
    AddRowDeletionPolicy(RowDeletionPolicy),
    ReplaceRowDeletionPolicy(RowDeletionPolicy),
    DropRowDeletionPolicy,
    AddSynonym(String),
    DropSynonym(String),
    Rename {
        to: String,
    },
    /// `RENAME TO new, ADD SYNONYM old`.
    RenameWithSynonym {
        to: String,
        synonym: String,
    },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AlterIndex {
    AddStoredColumn(String),
    DropStoredColumn(String),
}

/// The schema of one database. Names are case-insensitive in Spanner; maps are keyed by lowercase
/// name and the objects keep their declared spelling.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Schema {
    pub schemas: BTreeMap<String, String>,
    pub tables: BTreeMap<String, Table>,
    pub indexes: BTreeMap<String, Index>,
    pub search_indexes: BTreeMap<String, SearchIndex>,
    pub sequences: BTreeMap<String, Sequence>,
    pub views: BTreeMap<String, View>,
    /// In declaration order.
    pub opaque: Vec<OpaqueObject>,
    pub options: Vec<(String, String)>,
    /// Bumped on every successful apply; lets SQL caches key on it.
    pub version: u64,
    /// Database name as written in the last `ALTER DATABASE`.
    pub database_name: Option<String>,
    /// Creation order of schemas, sequences, tables and views (lowercase keys); drives `to_ddl`.
    pub creation_order: Vec<(ObjectKind, String)>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum ObjectKind {
    Schema,
    Sequence,
    Table,
    View,
}

impl Schema {
    pub fn table(&self, name: &str) -> Option<&Table> {
        self.tables.get(&name.to_ascii_lowercase())
    }

    pub fn index(&self, name: &str) -> Option<&Index> {
        self.indexes.get(&name.to_ascii_lowercase())
    }

    /// Indexes on a table.
    pub fn indexes_on<'a>(&'a self, table: &'a str) -> impl Iterator<Item = &'a Index> + 'a {
        self.indexes
            .values()
            .filter(move |i| i.table.eq_ignore_ascii_case(table))
    }
}
