const DEFAULT_MAX_ALLOWED_GAP: i64 = 5;

fn not_match(func: &str, tokenizer: &str) -> Error {
    Error::invalid_argument(format!(
        "{func} function's first argument must be a TOKENLIST column generated by {tokenizer}"
    ))
}

fn ret_check(line: u32, cond: &str) -> Error {
    Error::new(
        Code::Internal,
        format!("GOOGLESQL_RET_CHECK failure (backend/query/search/{cond}:{line})"),
    )
}

fn invalid_query_type(v: &Value) -> Option<Error> {
    match v {
        Value::Bytes(_) => Some(Error::invalid_argument("Invalid search query type: BYTES.")),
        _ => None,
    }
}

type TokenMap<'a> = HashMap<&'a [u8], Vec<i64>>;

/// `SearchHelper::BuildTokenMap`: token positions, and whether the tokenized source was NULL.
fn token_map<'a>(toks: &[&'a [u8]], func: &str) -> Result<(TokenMap<'a>, bool)> {
    if toks.first().is_none_or(|t| t.is_empty()) {
        return Err(ret_check(
            95,
            "search_evaluator_helpers.cc) !tokens.empty() && !tokens[0].empty(",
        ));
    }
    let mut map: TokenMap = HashMap::new();
    let (mut sigs, mut pos, mut source_null) = (0i64, 0i64, false);
    for &t in toks {
        if is_signature(t) {
            let parts: Vec<&[u8]> = t.split(|&c| c == b'-').filter(|p| !p.is_empty()).collect();
            if parts[0] != FULLTEXT.as_bytes() {
                return Err(not_match(func, "TOKENIZE_FULLTEXT"));
            }
            source_null = pos == 0 && parts.get(1) != Some(&&b"0"[..]);
            sigs += 1;
        } else if pos == 0 {
            return Err(not_match(func, "TOKENIZE_FULLTEXT"));
        } else if t == GAP {
            pos += 1000;
        } else {
            map.entry(t).or_default().push(pos - sigs);
        }
        pos += 1;
    }
    Ok((map, source_null))
}

/// `GetNormalizedTerms`.
fn normalized_terms(q: &str) -> Vec<Vec<u8>> {
    split(q.as_bytes())
        .map(|t| match std::str::from_utf8(t) {
            Ok(t) => lower(t).into_bytes(),
            Err(_) => t.to_vec(),
        })
        .collect()
}

#[derive(PartialEq)]
enum Dialect {
    RQuery,
    Words,
    WordsPhrase,
}

fn dialect(args: &[Value]) -> Result<Dialect> {
    match str_arg(args, 4) {
        None => Ok(Dialect::RQuery),
        Some(d) if d.eq_ignore_ascii_case("rquery") => Ok(Dialect::RQuery),
        Some(d) if d.eq_ignore_ascii_case("words") => Ok(Dialect::Words),
        Some(d) if d.eq_ignore_ascii_case("words_phrase") => Ok(Dialect::WordsPhrase),
        Some(d) => Err(Error::invalid_argument(format!("Invalid dialect: {d}"))),
    }
}

/// A query string prepared once: its rquery tree and the terms SCORE counts.
pub(super) struct Compiled {
    pub(super) parse: Result<Option<Node>>,
    /// The distinct terms of a tree without phrases or AROUND, which only needs term presence.
    simple: Option<Vec<Vec<u8>>>,
    /// Every distinct term of the tree.
    terms: Vec<Vec<u8>>,
    /// `GetNormalizedTerms` of the query.
    words: Vec<Vec<u8>>,
    /// Prod's SCORE terms (from the query before stopwords are dropped); `None` in emulator mode.
    score: Option<ScoreQuery>,
}

fn collect_simple(n: &Node, out: &mut Vec<Vec<u8>>) -> bool {
    match n {
        Node::Term(t) => {
            if !out.contains(t) {
                out.push(t.clone());
            }
            true
        }
        Node::And(c) | Node::Or(c) => c.iter().all(|c| collect_simple(c, out)),
        Node::Not(c) => collect_simple(c, out),
        Node::Number(_) | Node::Phrase(_) | Node::Around(_) => false,
    }
}

fn eval_simple(n: &Node, present: &dyn Fn(&[u8]) -> bool) -> bool {
    match n {
        Node::Term(t) => present(t),
        Node::And(c) => c.iter().all(|c| eval_simple(c, present)),
        Node::Or(c) => c.iter().any(|c| eval_simple(c, present)),
        Node::Not(c) => !eval_simple(c, present),
        Node::Number(_) | Node::Phrase(_) | Node::Around(_) => false,
    }
}

/// Prepared queries, shared across statements like the emulator's `SearchQueryCache`.
/// Keyed by (emulator mode, query text).
type QueryCache = HashMap<(bool, String), Arc<Compiled>>;

static QUERIES: LazyLock<Mutex<QueryCache>> = LazyLock::new(|| Mutex::new(HashMap::new()));

pub(super) fn cache_len() -> usize {
    QUERIES.lock().map_or(0, |c| c.len())
}

fn compiled(q: &str, emulator: bool) -> Arc<Compiled> {
    let key = (emulator, q.to_string());
    if let Ok(c) = QUERIES.lock()
        && let Some(n) = c.get(&key)
    {
        return n.clone();
    }
    let parse = rquery::parse(q, emulator);
    let score = match &parse {
        Ok(Some(n)) if !emulator => Some(ScoreQuery::new(n)),
        _ => None,
    };
    // Prod drops stopwords from SEARCH queries.
    let parse = if emulator {
        parse
    } else {
        parse.map(|n| n.map(score::drop_stopwords))
    };
    let simple = match &parse {
        Ok(Some(n)) => {
            let mut terms = Vec::new();
            collect_simple(n, &mut terms).then_some(terms)
        }
        _ => None,
    };
    let mut terms = Vec::new();
    if let Ok(Some(n)) = &parse {
        collect_terms(n, &mut terms);
    }
    let n = Arc::new(Compiled {
        parse,
        simple,
        terms,
        words: normalized_terms(q),
        score,
    });
    if let Ok(mut c) = QUERIES.lock() {
        if c.len() >= 4096 {
            c.clear();
        }
        c.insert(key, n.clone());
    }
    n
}

/// One pass over a fulltext TOKENLIST with `BuildTokenMap`'s validation, collecting the
/// positions of `terms` only. Returns whether the tokenized source was NULL.
fn term_positions(
    bytes: &[u8],
    func: &str,
    terms: &[Vec<u8>],
    out: &mut [Vec<i64>],
) -> Result<bool> {
    let (mut source_null, mut first) = (false, true);
    let (mut pos, mut sigs) = (0i64, 0i64);
    for t in tokens::iter(bytes) {
        let t = t?;
        if first && t.is_empty() {
            break;
        }
        if is_signature(t) {
            let mut parts = t.split(|&c| c == b'-').filter(|p| !p.is_empty());
            if parts.next() != Some(FULLTEXT.as_bytes()) {
                return Err(not_match(func, "TOKENIZE_FULLTEXT"));
            }
            source_null = first && parts.next() != Some(&b"0"[..]);
            sigs += 1;
        } else if first {
            return Err(not_match(func, "TOKENIZE_FULLTEXT"));
        } else if t == GAP {
            pos += 1000;
        } else {
            for (i, term) in terms.iter().enumerate() {
                if term.as_slice() == t {
                    out[i].push(pos - sigs);
                }
            }
        }
        first = false;
        pos += 1;
    }
    if first {
        return Err(ret_check(
            95,
            "search_evaluator_helpers.cc) !tokens.empty() && !tokens[0].empty(",
        ));
    }
    Ok(source_null)
}

fn collect_terms(n: &Node, out: &mut Vec<Vec<u8>>) {
    match n {
        Node::Term(t) => {
            if !out.contains(t) {
                out.push(t.clone());
            }
        }
        Node::And(c) | Node::Or(c) | Node::Phrase(c) | Node::Around(c) => {
            c.iter().for_each(|c| collect_terms(c, out))
        }
        Node::Not(c) => collect_terms(c, out),
        Node::Number(_) => {}
    }
}

/// Query text, emulator mode and the compiled query.
type LastQuery = (Arc<str>, bool, Arc<Compiled>);

thread_local! {
    static LAST: std::cell::RefCell<Option<LastQuery>> =
        const { std::cell::RefCell::new(None) };
}

/// `compiled`, remembering the last query per thread (a statement evaluates one query per row).
pub(super) fn compiled_for(q: &Arc<str>, emulator: bool) -> Arc<Compiled> {
    LAST.with(|l| {
        let mut l = l.borrow_mut();
        if let Some((k, e, c)) = l.as_ref()
            && *e == emulator
            && (Arc::ptr_eq(k, q) || **k == **q)
        {
            return c.clone();
        }
        let c = compiled(q, emulator);
        *l = Some((q.clone(), emulator, c.clone()));
        c
    })
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
struct Hit {
    pos: i64,
    width: i64,
}

impl Hit {
    fn limit(&self) -> i64 {
        self.pos + self.width
    }
}

/// `None` is no match; `Some(hits)` a match (hits empty outside phrases).
type Match = Option<Vec<Hit>>;

fn sorted_unique(mut h: Vec<Hit>) -> Vec<Hit> {
    h.sort();
    h.dedup();
    h
}

enum Mode {
    Phrase {
        offsets: Vec<i64>,
        exterior: (i64, i64),
    },
    Unear {
        max_gap: i64,
        max_widths: Vec<i64>,
    },
}

struct PhraseMatcher<'a> {
    mode: Mode,
    inputs: &'a [Vec<Hit>],
    partial: Vec<Hit>,
}

impl PhraseMatcher<'_> {
    fn find(&mut self) -> Vec<Hit> {
        let mut out = Vec::new();
        self.find_internal(&mut out);
        sorted_unique(out)
    }

    fn find_internal(&mut self, out: &mut Vec<Hit>) {
        if self.partial.len() == self.inputs.len() {
            if matches!(self.mode, Mode::Unear { .. }) && self.overlaps() {
                return;
            }
            let min_pos = self.partial.iter().map(|h| h.pos).min().unwrap_or(0);
            let max_limit = self.partial.iter().map(Hit::limit).max().unwrap_or(0);
            let ext = match &self.mode {
                Mode::Phrase { exterior, .. } => *exterior,
                Mode::Unear { .. } => (0, 0),
            };
            out.push(Hit {
                pos: min_pos - ext.0,
                width: max_limit - min_pos + ext.0 + ext.1,
            });
            return;
        }
        let (min_pos, max_pos, min_limit) = self.requirements();
        let idx = self.partial.len();
        let input = &self.inputs[idx];
        let start = input.partition_point(|h| {
            *h < Hit {
                pos: min_pos,
                width: 1,
            }
        });
        for h in &input[start..] {
            if h.pos > max_pos {
                break;
            }
            if min_limit.is_some_and(|m| h.limit() < m) {
                continue;
            }
            self.partial.push(*h);
            self.find_internal(out);
            self.partial.pop();
        }
    }

    fn requirements(&self) -> (i64, i64, Option<i64>) {
        let Some(last) = self.partial.last() else {
            return (i64::MIN, i64::MAX, None);
        };
        let next = self.partial.len();
        match &self.mode {
            Mode::Phrase { offsets, .. } => {
                let p = last.limit() + (offsets[next] - offsets[next - 1] - 1);
                (p, p, None)
            }
            Mode::Unear {
                max_gap,
                max_widths,
            } => {
                let max_p = self.partial.iter().map(|h| h.pos).max().unwrap_or(0);
                let min_l = self.partial.iter().map(Hit::limit).min().unwrap_or(0);
                (
                    max_p - max_gap - max_widths[next],
                    min_l + max_gap,
                    Some(max_p - max_gap),
                )
            }
        }
    }

    fn overlaps(&self) -> bool {
        let mut s = self.partial.clone();
        s.sort();
        s.windows(2).any(|w| w[1].pos < w[0].limit())
    }
}

fn match_children(c: &[Node], map: &TokenMap, in_phrase: bool) -> Result<Vec<Match>> {
    c.iter()
        .filter(|n| !matches!(n, Node::Number(_)))
        .map(|n| match_node(n, map, in_phrase))
        .collect()
}

fn match_node(n: &Node, map: &TokenMap, in_phrase: bool) -> Result<Match> {
    Ok(match n {
        Node::Number(_) => None,
        Node::Term(t) => match map.get(t.as_slice()) {
            None => None,
            Some(_) if !in_phrase => Some(Vec::new()),
            Some(ps) => Some(sorted_unique(
                ps.iter().map(|&pos| Hit { pos, width: 1 }).collect(),
            )),
        },
        Node::Or(c) => {
            let mut any = false;
            let mut hits = Vec::new();
            for r in match_children(c, map, in_phrase)?.into_iter().flatten() {
                any = true;
                if in_phrase {
                    hits.extend(r);
                }
            }
            any.then(|| sorted_unique(hits))
        }
        Node::Not(c) => {
            if in_phrase {
                return Err(Error::new(
                    Code::Internal,
                    "GOOGLESQL_RET_CHECK failure (backend/query/search/search_evaluator.cc:152) !in_phrase NOT nodes cannot appear in phrases",
                ));
            }
            match match_node(c, map, false)? {
                Some(_) => None,
                None => Some(Vec::new()),
            }
        }
        Node::And(c) => {
            if in_phrase {
                return Err(Error::new(
                    Code::Internal,
                    "GOOGLESQL_RET_CHECK failure (backend/query/search/search_evaluator.cc:164) !in_phrase AND nodes cannot appear in phrases",
                ));
            }
            if match_children(c, map, false)?.iter().any(Option::is_none) {
                None
            } else {
                Some(Vec::new())
            }
        }
        Node::Around(c) => {
            let results = match_children(c, map, true)?;
            let mut max_gap = -1;
            let mut hits = Vec::new();
            let mut r = results.into_iter();
            for child in c {
                if let Node::Number(g) = child {
                    if max_gap == -1 {
                        max_gap = *g;
                    } else if *g != max_gap {
                        max_gap = DEFAULT_MAX_ALLOWED_GAP;
                    }
                } else {
                    match r.next().flatten() {
                        Some(h) => hits.push(h),
                        None => return Ok(None),
                    }
                }
            }
            if max_gap == -1 {
                return Err(Error::invalid_argument(
                    "Invalid distance specified in AROUND expression.",
                ));
            }
            let max_widths = hits
                .iter()
                .map(|hs| hs.iter().map(|h| h.width).max().unwrap_or(1).max(1))
                .collect();
            let found = PhraseMatcher {
                mode: Mode::Unear {
                    max_gap,
                    max_widths,
                },
                inputs: &hits,
                partial: Vec::new(),
            }
            .find();
            (!found.is_empty()).then_some(found)
        }
        Node::Phrase(c) => {
            let results = match_children(c, map, true)?;
            let mut hits = Vec::new();
            let mut offsets = Vec::new();
            for (i, r) in results.into_iter().enumerate() {
                match r {
                    Some(h) => hits.push(h),
                    None => return Ok(None),
                }
                offsets.push(i as i64);
            }
            let found = PhraseMatcher {
                mode: Mode::Phrase {
                    offsets,
                    exterior: (0, 0),
                },
                inputs: &hits,
                partial: Vec::new(),
            }
            .find();
            (!found.is_empty()).then_some(found)
        }
    })
}

fn tokenlist(v: &Value) -> Result<Option<Vec<&[u8]>>> {
    match v {
        Value::TokenList(b) => Ok(Some(decode(b)?)),
        _ => Ok(None),
    }
}

pub fn search(args: &[Value], emulator: bool) -> Result<Value> {
    if let Some(e) = invalid_query_type(&args[1]) {
        return Err(e);
    }
    if let (Value::TokenList(b), Value::String(q)) = (&args[0], &args[1])
        && !q.is_empty()
        && str_arg(args, 4).is_none_or(|d| d.eq_ignore_ascii_case("rquery"))
    {
        let c = compiled_for(q, emulator);
        if let Ok(Some(n)) = &c.parse {
            let mut pos = vec![Vec::new(); c.terms.len()];
            if term_positions(b, "SEARCH", &c.terms, &mut pos)? {
                return Ok(Value::Null);
            }
            if !emulator && rquery::only_negations(n) {
                return Ok(Value::Bool(false));
            }
            if c.simple.is_some() {
                let present = |t: &[u8]| {
                    c.terms
                        .iter()
                        .position(|x| x.as_slice() == t)
                        .is_some_and(|i| !pos[i].is_empty())
                };
                return Ok(Value::Bool(eval_simple(n, &present)));
            }
            let map: TokenMap = c
                .terms
                .iter()
                .zip(pos)
                .filter(|(_, p)| !p.is_empty())
                .map(|(t, p)| (t.as_slice(), p))
                .collect();
            return Ok(Value::Bool(match_node(n, &map, false)?.is_some()));
        }
    }
    let toks = tokenlist(&args[0])?;
    let (map, source_null) = match &toks {
        Some(t) => token_map(t, "SEARCH")?,
        None => (HashMap::new(), false),
    };
    let Value::String(q) = &args[1] else {
        return Ok(Value::Null);
    };
    if source_null {
        return Ok(Value::Null);
    }
    if q.is_empty() {
        return Ok(Value::Bool(false));
    }
    match dialect(args)? {
        Dialect::Words => {
            let terms = normalized_terms(q);
            Ok(Value::Bool(
                !terms.is_empty() && terms.iter().all(|t| map.contains_key(t.as_slice())),
            ))
        }
        Dialect::WordsPhrase => {
            let terms = normalized_terms(q);
            let toks = toks.unwrap_or_default();
            Ok(Value::Bool(
                !terms.is_empty()
                    && toks.len() >= terms.len()
                    && toks
                        .windows(terms.len())
                        .any(|w| w.iter().zip(&terms).all(|(a, b)| *a == b.as_slice())),
            ))
        }
        Dialect::RQuery => {
            let c = compiled_for(q, emulator);
            Ok(Value::Bool(match &c.parse {
                Ok(Some(n)) if !emulator && rquery::only_negations(n) => false,
                Ok(Some(n)) => match_node(n, &map, false)?.is_some(),
                Ok(None) => false,
                Err(e) => return Err(e.clone()),
            }))
        }
    }
}

pub fn score(args: &[Value], emulator: bool) -> Result<Value> {
    if let Some(e) = invalid_query_type(&args[1]) {
        return Err(e);
    }
    if !emulator {
        return score_prod(args);
    }
    let counted = str_arg(args, 4)
        .is_none_or(|d| d.eq_ignore_ascii_case("rquery") || d.eq_ignore_ascii_case("words"));
    if let (Value::TokenList(b), Value::String(q)) = (&args[0], &args[1])
        && counted
    {
        let c = compiled_for(q, emulator);
        let mut counts = vec![Vec::new(); c.words.len()];
        if term_positions(b, "SCORE", &c.words, &mut counts)? {
            return Ok(Value::Float64(0.0));
        }
        return Ok(Value::Float64(counts.iter().map(|p| p.len() as f64).sum()));
    }
    let toks = tokenlist(&args[0])?;
    let (map, source_null) = match &toks {
        Some(t) => token_map(t, "SCORE")?,
        None => (HashMap::new(), false),
    };
    let Value::String(q) = &args[1] else {
        return Ok(Value::Float64(0.0));
    };
    if source_null {
        return Ok(Value::Float64(0.0));
    }
    let terms = normalized_terms(q);
    let score = if dialect(args)? == Dialect::WordsPhrase {
        let toks = toks.unwrap_or_default();
        if terms.is_empty() || toks.len() < terms.len() {
            0.0
        } else {
            toks.windows(terms.len())
                .filter(|w| w.iter().zip(&terms).all(|(a, b)| *a == b.as_slice()))
                .count() as f64
        }
    } else {
        terms
            .iter()
            .map(|t| map.get(t.as_slice()).map_or(0, Vec::len) as f64)
            .sum()
    };
    Ok(Value::Float64(score))
}

/// Cloud Spanner's SCORE (see `score`): the same for every dialect, which only changes how the
/// query is read.
fn score_prod(args: &[Value]) -> Result<Value> {
    let words_query = |phrase: bool| -> Option<ScoreQuery> {
        let Value::String(q) = &args[1] else {
            return None;
        };
        let terms: Vec<Node> = normalized_terms(q).into_iter().map(Node::Term).collect();
        (!terms.is_empty()).then(|| {
            ScoreQuery::new(&if phrase {
                Node::Phrase(terms)
            } else {
                Node::And(terms)
            })
        })
    };
    let (Value::TokenList(b), Value::String(q)) = (&args[0], &args[1]) else {
        // Validates the dialect and the source's tokenizer.
        dialect(args)?;
        if let Some(t) = tokenlist(&args[0])? {
            token_map(&t, "SCORE")?;
        }
        return Ok(Value::Float64(0.0));
    };
    let compiled;
    let owned;
    let sq = match dialect(args)? {
        Dialect::RQuery => {
            compiled = compiled_for(q, false);
            if let Err(e) = &compiled.parse {
                return Err(e.clone());
            }
            compiled.score.as_ref()
        }
        Dialect::Words => {
            owned = words_query(false);
            owned.as_ref()
        }
        Dialect::WordsPhrase => {
            owned = words_query(true);
            owned.as_ref()
        }
    };
    let Some(sq) = sq else {
        if let Some(t) = tokenlist(&args[0])? {
            token_map(&t, "SCORE")?;
        }
        return Ok(Value::Float64(0.0));
    };
    let mut pos = vec![Vec::new(); sq.terms.len()];
    if term_positions(b, "SCORE", &sq.terms, &mut pos)? {
        return Ok(Value::Float64(0.0));
    }
    Ok(Value::Float64(sq.score(&pos)))
}

fn split_sig(t: &[u8]) -> Vec<&[u8]> {
    t.split(|&c| c == b'-').filter(|p| !p.is_empty()).collect()
}

fn sig_int(p: &[&[u8]], i: usize) -> Option<i64> {
    std::str::from_utf8(p.get(i)?).ok()?.parse().ok()
}

pub fn search_substring(args: &[Value], emulator: bool) -> Result<Value> {
    let Some(toks) = tokenlist(&args[0])? else {
        return Ok(Value::Null);
    };
    let mut min_size = 12;
    let mut types = 0;
    let mut source_null = false;
    let mut words: Vec<&[u8]> = Vec::new();
    for (i, &t) in toks.iter().enumerate() {
        if is_signature(t) {
            if !t.starts_with(SUBSTRING.as_bytes()) {
                return Err(not_match("SEARCH_SUBSTRING", "TOKENIZE_SUBSTRING"));
            }
            let p = split_sig(t);
            let (Some(min), Some(ty)) = (sig_int(&p, 2), sig_int(&p, 4)) else {
                return Err(ret_check(57, "search_substring_evaluator.cc)"));
            };
            if p.len() != 5 || min <= 0 {
                return Err(ret_check(57, "search_substring_evaluator.cc)"));
            }
            types = ty;
            source_null = p[3] != b"0";
            min_size = min_size.min(min);
        } else if i == 0 {
            return Err(not_match("SEARCH_SUBSTRING", "TOKENIZE_SUBSTRING"));
        } else {
            words.extend(split(t));
        }
    }
    let mut requested = 0;
    if let Some(r) = str_arg(args, 2) {
        requested = tokens::parse_relative_search_type(r).map_err(|e| {
            if emulator {
                e
            } else {
                Error::invalid_argument(format!(
                    "{} Valid relative_search_type values: ['value_prefix', 'value_suffix', 'word_prefix', 'word_suffix', 'phrase']",
                    e.message
                ))
            }
        })?;
        if types & requested == 0 {
            let q = if emulator { '\'' } else { '`' };
            return Err(Error::invalid_argument(format!(
                "The referenced substring TOKENLIST is not tokenized with {q}{r}{q} support."
            )));
        }
    }
    let Value::String(q) = &args[1] else {
        return Ok(Value::Null);
    };
    if source_null {
        return Ok(Value::Null);
    }
    let lq = lower(q);
    let subs: Vec<&[u8]> = split(lq.as_bytes()).collect();
    if subs.is_empty() {
        return Ok(Value::Bool(false));
    }
    // The emulator gives up on several words with a relative search type; prod applies it to each.
    if emulator && subs.len() > 1 && requested != PHRASE && requested != 0 {
        return Ok(Value::Null);
    }
    let min_size = min_size as usize;
    if requested == PHRASE {
        let mut phrase = subs.join(&b' ');
        if phrase.len() < min_size {
            phrase = [&b" "[..], &phrase, b" "].concat();
        }
        let mut doc = vec![b' '];
        doc.extend(words.join(&b' '));
        doc.push(b' ');
        return Ok(Value::Bool(
            phrase.len() >= min_size && contains(&doc, &phrase),
        ));
    }
    let set: HashSet<&[u8]> = words.iter().copied().collect();
    for ss in subs {
        let found = (set.contains(ss) || ss.len() >= min_size)
            && !words.is_empty()
            && match requested {
                0 => words.iter().any(|w| contains(w, ss)),
                WORD_PREFIX => words.iter().any(|w| w.starts_with(ss)),
                WORD_SUFFIX => words.iter().any(|w| w.ends_with(ss)),
                VALUE_PREFIX => words[0].starts_with(ss),
                VALUE_SUFFIX => words[words.len() - 1].ends_with(ss),
                _ => false,
            };
        if !found {
            return Ok(Value::Bool(false));
        }
    }
    Ok(Value::Bool(true))
}

fn contains(hay: &[u8], needle: &[u8]) -> bool {
    needle.is_empty() || hay.windows(needle.len()).any(|w| w == needle)
}

/// Lower-cased byte n-grams; tokens cut inside a UTF-8 character are used as they are.
fn ngrams(s: &[u8], min: i64, max: i64) -> Vec<Vec<u8>> {
    let mut out = Vec::new();
    match std::str::from_utf8(s) {
        Ok(t) => tokens::ngrams_of(lower(t).as_bytes(), min, max, &mut out),
        Err(_) => tokens::ngrams_of(s, min, max, &mut out),
    }
    out
}

const NGRAM_FUNCS: &str = "TOKENIZE_SUBSTRING or TOKENIZE_NGRAMS";

pub fn search_ngrams(args: &[Value], emulator: bool) -> Result<Value> {
    let min_ngrams = int_arg(args, 2, 2);
    let percent = match arg(args, 3) {
        Some(Value::Float64(v)) => *v,
        _ => 0.0,
    };
    let (Some(toks), Value::String(q)) = (tokenlist(&args[0])?, &args[1]) else {
        return Ok(Value::Null);
    };
    let mut tl: Vec<Vec<u8>> = Vec::new();
    let mut qn: HashSet<Vec<u8>> = HashSet::new();
    let (mut max, mut min, mut substring, mut source_null) = (-1, -1, false, false);
    let mut words: Vec<&[u8]> = Vec::new();
    for (i, &t) in toks.iter().enumerate() {
        if is_signature(t) {
            substring = t.starts_with(SUBSTRING.as_bytes());
            if !substring && !t.starts_with(NGRAMS.as_bytes()) {
                return Err(not_match("SEARCH_NGRAMS", NGRAM_FUNCS));
            }
            let p = split_sig(t);
            match (sig_int(&p, 1), sig_int(&p, 2)) {
                (Some(a), Some(b)) if p.len() == 4 || p.len() == 5 => (max, min) = (a, b),
                _ => return Err(ret_check(70, "search_ngrams_evaluator.cc)")),
            }
            source_null = p[3] != b"0";
            // Prod's TOKENIZE_NGRAMS keeps case, and so does the query over it.
            let fold = emulator || substring;
            for w in split(q.as_bytes()) {
                let n = (w.len() as i64).min(max);
                if fold {
                    qn.extend(ngrams(w, n, max));
                } else {
                    let mut out = Vec::new();
                    tokens::ngrams_of(w, n, max, &mut out);
                    qn.extend(out);
                }
            }
        } else if t == GAP {
            continue;
        } else if i == 0 {
            return Err(not_match("SEARCH_NGRAMS", NGRAM_FUNCS));
        } else if substring {
            words.extend(split(t));
        } else {
            tl.push(t.to_vec());
        }
    }
    if substring {
        for w in words {
            tokens::ngrams_of(w, min, max, &mut tl);
        }
    }
    if source_null {
        return Ok(Value::Null);
    }
    let tl: HashSet<Vec<u8>> = tl.into_iter().collect();
    let matching = qn.iter().filter(|g| tl.contains(*g)).count() as i64;
    let mut min_ngrams = min_ngrams;
    if (qn.len() as i64) < min_ngrams {
        min_ngrams = (qn.len() as i64).max(1);
    }
    let mut matches = matching >= min_ngrams;
    if matching < (qn.len() as f64 * percent / 100.0).ceil() as i64 {
        matches = false;
    }
    Ok(Value::Bool(matches))
}

pub fn score_ngrams(args: &[Value], emulator: bool) -> Result<Value> {
    if !emulator {
        return score_ngrams_prod(args);
    }
    let (Some(toks), Value::String(q)) = (tokenlist(&args[0])?, &args[1]) else {
        return Ok(Value::Float64(0.0));
    };
    let mut tl: HashSet<Vec<u8>> = HashSet::new();
    let mut qt: HashSet<Vec<u8>> = HashSet::new();
    let mut source_null = false;
    for (i, &t) in toks.iter().enumerate() {
        if is_signature(t) {
            if !t.starts_with(SUBSTRING.as_bytes()) && !t.starts_with(NGRAMS.as_bytes()) {
                return Err(not_match("SCORE_NGRAMS", NGRAM_FUNCS));
            }
            let p = split_sig(t);
            if p.len() != 4 && p.len() != 5 {
                return Err(ret_check(55, "score_ngrams_evaluator.cc)"));
            }
            source_null = p[3] != b"0";
            qt.extend(ngrams(q.as_bytes(), 3, 3));
        } else if t == GAP {
            continue;
        } else if i == 0 {
            return Err(not_match("SCORE_NGRAMS", NGRAM_FUNCS));
        } else {
            tl.extend(ngrams(t, 3, 3));
        }
    }
    if source_null {
        return Ok(Value::Float64(0.0));
    }
    let m = qt.iter().filter(|g| tl.contains(*g)).count() as f64;
    Ok(Value::Float64(m / (qt.len() as f64 + tl.len() as f64 - m)))
}

/// Character trigrams of `chars` padded with `pre` and `post`.
fn trigrams(pre: &str, text: &str, post: &str, out: &mut HashSet<[char; 3]>) {
    let c: Vec<char> = pre
        .chars()
        .chain(text.chars())
        .chain(post.chars())
        .collect();
    out.extend(c.windows(3).map(|w| [w[0], w[1], w[2]]));
}

/// The text of one TOKENIZE_NGRAMS value from its n-grams (smallest size first, in order).
fn ngrams_text(grams: &[&[u8]], min: usize) -> String {
    let mut text: Vec<u8> = Vec::new();
    for g in grams.iter().take_while(|g| g.len() == min) {
        if text.is_empty() {
            text.extend_from_slice(g);
        } else if let Some(&b) = g.last() {
            text.push(b);
        }
    }
    String::from_utf8_lossy(&text).into_owned()
}

/// Cloud Spanner's SCORE_NGRAMS: the Jaccard index of character trigram sets of the whole query
/// and the whole value. Over TOKENIZE_NGRAMS both are padded as `^^` + text + `$` and keep their
/// case; over TOKENIZE_SUBSTRING both are lower-cased and padded as `"  "` + text + `" "`.
fn score_ngrams_prod(args: &[Value]) -> Result<Value> {
    let (Some(toks), Value::String(q)) = (tokenlist(&args[0])?, &args[1]) else {
        if let Some(toks) = tokenlist(&args[0])?
            && let Some(&first) = toks.first()
            && !(first.starts_with(SUBSTRING.as_bytes()) || first.starts_with(NGRAMS.as_bytes()))
        {
            return Err(not_match("SCORE_NGRAMS", NGRAM_FUNCS));
        }
        return Ok(Value::Float64(0.0));
    };
    let Some((&sig, values)) = toks.split_first() else {
        return Err(not_match("SCORE_NGRAMS", NGRAM_FUNCS));
    };
    let substring = sig.starts_with(SUBSTRING.as_bytes());
    if !is_signature(sig) || !(substring || sig.starts_with(NGRAMS.as_bytes())) {
        return Err(not_match("SCORE_NGRAMS", NGRAM_FUNCS));
    }
    let p = split_sig(sig);
    if p.len() != 4 && p.len() != 5 {
        return Err(ret_check(55, "score_ngrams_evaluator.cc)"));
    }
    if p[3] != b"0" {
        return Ok(Value::Float64(0.0));
    }
    let min = sig_int(&p, 2).unwrap_or(1).max(1) as usize;
    let mut doc = HashSet::new();
    let mut query = HashSet::new();
    for value in values.split(|t| *t == GAP) {
        if substring {
            for t in value {
                // Prod scores the words of the value joined by single spaces.
                let words: Vec<&[u8]> = split(t).collect();
                trigrams(
                    "  ",
                    &String::from_utf8_lossy(&words.join(&b' ')),
                    " ",
                    &mut doc,
                );
            }
        } else if !value.is_empty() {
            trigrams("^^", &ngrams_text(value, min), "$", &mut doc);
        }
    }
    if substring {
        let lq = lower(q);
        let words: Vec<&[u8]> = split(lq.as_bytes()).collect();
        trigrams(
            "  ",
            &String::from_utf8_lossy(&words.join(&b' ')),
            " ",
            &mut query,
        );
    } else {
        trigrams("^^", q, "$", &mut query);
    }
    let m = query.intersection(&doc).count() as f64;
    let union = query.len() as f64 + doc.len() as f64 - m;
    Ok(Value::Float64(if union == 0.0 { 0.0 } else { m / union }))
}

fn alnum(b: Option<&u8>) -> bool {
    b.is_some_and(u8::is_ascii_alphanumeric)
}

pub fn snippet(args: &[Value], emulator: bool) -> Result<Value> {
    if emulator {
        snippet_emulator(args)
    } else {
        snippet_prod(args)
    }
}

/// Cloud Spanner's SNIPPET: character offsets, `{"begin","end"}` highlights (1-based, end
/// exclusive, relative to the snippet), the snippet's `source_begin`/`source_end` in the source,
/// trailing punctuation dropped, tags stripped for `text/html`, and no snippet for empty text.
fn snippet_prod(args: &[Value]) -> Result<Value> {
    let html = match str_arg(args, 6) {
        None => false,
        Some(ct) if ct.eq_ignore_ascii_case("text/html") => true,
        Some(ct) if ct.eq_ignore_ascii_case("text/plain") => false,
        Some(ct) => {
            return Err(Error::invalid_argument(format!(
                "Invalid use of SNIPPET: content_type. '{ct}' is not a supported content type. Supported options:[text/html, text/plain]"
            )));
        }
    };
    let (Value::String(target), Value::String(query)) = (&args[0], &args[1]) else {
        return Ok(Value::Null);
    };
    let int = |i: usize, d: i64, name: &str| -> Result<i64> {
        let v = int_arg(args, i, d) as i32 as i64;
        if v <= 0 {
            return Err(Error::invalid_argument(format!(
                "SNIPPET has out of range value for {name} argument."
            )));
        }
        Ok(v)
    };
    let width = int(4, 160, "max_snippet_width")? as usize;
    int(5, 3, "max_snippets")?;
    // The text the snippet is cut from, and each character's index in the source.
    let mut text = String::with_capacity(target.len());
    let mut source: Vec<usize> = Vec::with_capacity(target.len());
    let mut in_tag = false;
    for (i, c) in target.chars().enumerate() {
        if html && in_tag {
            in_tag = c != '>';
        } else if html && c == '<' {
            in_tag = true;
        } else {
            text.push(c);
            source.push(i);
        }
    }
    if text.is_empty() {
        return Ok(Value::Json(Arc::from("{\"snippets\":[]}")));
    }
    let chars: Vec<char> = text.chars().collect();
    let alnum = |i: usize| chars.get(i).is_some_and(|c| c.is_alphanumeric());
    // Character index of every byte offset that starts a character.
    let mut char_at = vec![0usize; text.len() + 1];
    for (n, (b, _)) in text.char_indices().enumerate() {
        char_at[b] = n;
    }
    char_at[text.len()] = chars.len();
    let terms: Vec<String> = split(query.as_bytes())
        .map(|t| regex::escape(&String::from_utf8_lossy(t)))
        .collect();
    let mut matches: Vec<(usize, usize)> = Vec::new();
    if !terms.is_empty() {
        let re = regex::Regex::new(&format!("(?i)\\b({})\\b", terms.join("|")))
            .map_err(|e| Error::internal(format!("snippet pattern: {e}")))?;
        matches = re
            .find_iter(&text)
            .map(|m| (char_at[m.start()], char_at[m.end()]))
            .collect();
    }
    let first = matches.first().map_or(0, |m| m.0);
    let len = chars.len();
    let mut end = len;
    if end - first >= width {
        // Cut at the width and drop the last word, which the cut may have split.
        end = first + width - 1;
        while end > first && alnum(end - 1) {
            end -= 1;
        }
        while end > first && !alnum(end - 1) {
            end -= 1;
        }
        if end == first {
            end = first + width - 1;
        }
    }
    let mut begin = 0usize;
    if end > width {
        begin = end - width;
        while begin < end && alnum(begin) {
            begin += 1;
        }
        while begin < end && !alnum(begin) {
            begin += 1;
        }
    }
    while end > begin && !alnum(end - 1) {
        end -= 1;
    }
    let snip: String = chars[begin..end].iter().collect();
    let highlights: Vec<String> = matches
        .iter()
        .filter(|(s, e)| *s >= begin && *e <= end)
        .map(|(s, e)| format!("{{\"begin\":{},\"end\":{}}}", s - begin + 1, e - begin + 1))
        .collect();
    let source_begin = source.get(begin).map_or(1, |i| i + 1);
    let source_end = if end > begin {
        source[end - 1] + 2
    } else {
        source_begin
    };
    let snip = serde_json::to_string(&snip).map_err(|e| Error::internal(e.to_string()))?;
    Ok(Value::Json(Arc::from(format!(
        "{{\"snippets\":[{{\"highlights\":[{}],\"snippet\":{snip},\"source_begin\":{source_begin},\"source_end\":{source_end}}}]}}",
        highlights.join(",")
    ))))
}

fn snippet_emulator(args: &[Value]) -> Result<Value> {
    if let Some(ct) = str_arg(args, 6)
        && !ct.eq_ignore_ascii_case("text/html")
        && !ct.eq_ignore_ascii_case("text/plain")
    {
        return Err(Error::invalid_argument(format!(
            "Invalid use of SNIPPET: content_type. '{ct}' is not a supported content type. Supported options:[text/html, text/plain]"
        )));
    }
    let (Value::String(target), Value::String(query)) = (&args[0], &args[1]) else {
        return Ok(Value::Null);
    };
    let int = |i: usize, d: i64, name: &str| -> Result<i64> {
        let v = int_arg(args, i, d) as i32 as i64;
        if v <= 0 {
            return Err(Error::invalid_argument(format!(
                "SNIPPET has out of range value for {name} argument."
            )));
        }
        Ok(v)
    };
    let max_len = int(4, 160, "max_snippet_length")?;
    int(5, 3, "max_snippets")?;
    let t = target.as_bytes();
    let terms: Vec<&[u8]> = split(query.as_bytes()).collect();
    let min_term = terms.iter().map(|t| t.len() as i64).fold(max_len, i64::min);
    let mut highlights = Vec::new();
    let mut snip: &[u8] = b"";
    if terms.is_empty() || min_term < max_len {
        let mut first = 0usize;
        let mut matches = Vec::new();
        if !terms.is_empty() {
            let alts: Vec<String> = terms
                .iter()
                .map(|t| regex::escape(&String::from_utf8_lossy(t)))
                .collect();
            let re =
                regex::bytes::Regex::new(&format!("(?i)(?-u:\\b)({})(?-u:\\b)", alts.join("|")))
                    .map_err(|e| Error::internal(format!("snippet pattern: {e}")))?;
            let mut found = false;
            for m in re.find_iter(t) {
                if !found {
                    first = m.start();
                    found = true;
                }
                if (m.end() - first) as i64 >= max_len {
                    break;
                }
                matches.push((m.start(), m.end()));
            }
        }
        let ml = max_len as usize;
        let mut end = t.len();
        if end - first >= ml {
            end = first + ml - 1;
            while end != first && alnum(t.get(end)) {
                end -= 1;
            }
            while end != first && !alnum(t.get(end)) {
                end -= 1;
            }
            if end != first {
                end += 1;
            }
        }
        let mut begin = 0usize;
        if end > ml {
            begin = end - ml;
            while begin < t.len() && alnum(t.get(begin)) {
                begin += 1;
            }
            while begin < t.len() && !alnum(t.get(begin)) {
                begin += 1;
            }
        }
        snip = t.get(begin..end.max(begin)).unwrap_or(b"");
        for (s, e) in matches {
            highlights.push(format!(
                "{{\"end_position\":{},\"start_position\":{}}}",
                e as i64 - begin as i64 + 1,
                s as i64 - begin as i64 + 1
            ));
        }
    }
    let text = serde_json::to_string(&String::from_utf8_lossy(snip))
        .map_err(|e| Error::internal(e.to_string()))?;
    Ok(Value::Json(Arc::from(format!(
        "{{\"snippets\":[{{\"highlights\":[{}],\"snippet\":{text}}}]}}",
        highlights.join(",")
    ))))
}

#[cfg(test)]
