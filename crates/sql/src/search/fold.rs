//! Cloud Spanner's text normalisation before TOKENIZE_FULLTEXT and TOKENIZE_SUBSTRING cut tokens
//! (#140), fitted to `conformance/cases/sql/search_tokenizer_unicode.case`:
//! - a letter or decimal digit takes its compatibility form (`ﬁ` is `fi`, `ｶﾞ` is `ガ`, `𝐀` is
//!   `A`, `０` is `0`), except superscript and subscript letters (`ª`, `ʰ`); other characters
//!   keep theirs (`²`, `①`, `Ⅻ`, `™`);
//! - then full case folding (`ꭰ` is `Ꭰ`, `ᾳ` is `αι`, `ς` is `σ`), except that `ß` stays and `İ`
//!   is `i`;
//! - then NFC (`cafe\u{301}` is `café`).
//!
//! TOKENIZE_NGRAMS keeps the text as it is.

use unicode_normalization::UnicodeNormalization;

/// `s` normalised as Cloud Spanner's fulltext and substring tokenizers normalise it.
pub fn normalize(s: &str) -> String {
    if s.is_ascii() {
        return s.to_ascii_lowercase();
    }
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        push_folded(c, &mut out);
    }
    to_nfc(&mut out);
    out
}

/// Appends `c` normalised but for NFC (`to_nfc`).
pub fn push_folded(c: char, out: &mut String) {
    if compat(c) {
        unicode_normalization::char::decompose_compatible(c, |d| fold_char(d, out));
    } else {
        fold_char(c, out);
    }
}

/// Puts `s` in NFC.
pub fn to_nfc(s: &mut String) {
    if s.is_ascii()
        || unicode_normalization::is_nfc_quick(s.chars())
            == unicode_normalization::IsNormalized::Yes
    {
        return;
    }
    *s = s.nfc().collect();
}

/// Whether Cloud Spanner replaces `c` with its compatibility decomposition: letters (not
/// superscript or subscript ones) and decimal digits that have one.
fn compat(c: char) -> bool {
    !c.is_ascii()
        && COMPAT
            .binary_search_by(|&(a, b)| {
                if b < c {
                    std::cmp::Ordering::Less
                } else if a > c {
                    std::cmp::Ordering::Greater
                } else {
                    std::cmp::Ordering::Equal
                }
            })
            .is_ok()
}

/// Appends the full case folding of `c`, with Cloud Spanner's exceptions.
fn fold_char(c: char, out: &mut String) {
    match c {
        'ß' | 'ẞ' => out.push('ß'),
        'İ' => out.push('i'),
        // Cherokee folds to upper case.
        '\u{13a0}'..='\u{13f5}' => out.push(c),
        '\u{13f8}'..='\u{13fd}' => out.extend(char::from_u32(c as u32 - 8)),
        '\u{ab70}'..='\u{abbf}' => out.extend(char::from_u32(c as u32 - 0xab70 + 0x13a0)),
        _ if c.is_ascii() => out.push(c.to_ascii_lowercase()),
        _ => match FOLD.binary_search_by_key(&c, |&(k, _)| k) {
            Ok(i) => out.push_str(FOLD[i].1),
            Err(_) => out.extend(c.to_lowercase()),
        },
    }
}

