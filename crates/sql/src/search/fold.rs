#[cfg(test)]
mod tests {
    use super::normalize;

    #[test]
    fn normalizes_like_spanner() {
        for (text, want) in [
            ("Hello", "hello"),
            ("ﬁle", "file"),
            ("İstanbul", "istanbul"),
            ("i\u{307}", "i\u{307}"),
            ("ı", "ı"),
            ("Straße", "straße"),
            ("ẞ", "ß"),
            ("cafe\u{301}", "café"),
            ("ΣΑΣ ς", "σασ σ"),
            ("ᾈ", "ἀι"),
            ("ᾳ", "αι"),
            ("x\u{345}", "xι"),
            ("Ⅻ", "ⅻ"),
            ("Ⓐ", "ⓐ"),
            ("① ½ ² ㌀ ™ №", "① ½ ² ㌀ ™ №"),
            ("ｆｕｌｌ ０１ Ａ", "full 01 a"),
            ("ｶﾞ ｱｲ ｰ", "ガ アイ ー"),
            ("ĳ ŀ ℌ ℹ 𝐀 𝟘 ℵ ǲ ǅ", "ij l· h i a 0 א dz dž"),
            ("ª ʰ ᵃ ⁿ", "ª ʰ ᵃ ⁿ"),
            ("ꭰ Ꭰ", "Ꭰ Ꭰ"),
            ("µ K ſ ϐ ϑ ẛ ŉ", "μ k s β θ ṡ ʼn"),
            ("ǰ ΐ ẖ", "ǰ ΐ ẖ"),
            ("ﬓ ﬗ", "մն մխ"),
            ("ﬁ\u{301}", "fí"),
            ("e\u{301}\u{301}", "é\u{301}"),
            ("٣", "٣"),
        ] {
            assert_eq!(normalize(text), want, "{text:?}");
        }
    }
}
