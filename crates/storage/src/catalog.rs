//! Positional view of a schema, built once per schema version and shared by every state that uses it.

use std::collections::HashMap;
use std::sync::Arc;

use spanbolt_ddl::{ColumnType, Generated, OnDelete, Schema, SortOrder};

use crate::error::{Error, Result};
use crate::state::Target;

pub type TableId = usize;
pub type IndexId = usize;

#[derive(Debug, Clone)]
pub struct ColumnMeta {
    pub name: String,
    pub ty: ColumnType,
    pub not_null: bool,
    pub allow_commit_timestamp: bool,
    /// STRING/BYTES length limit (characters / bytes).
    pub max_len: Option<u64>,
    /// Any generated column (`AS (expr)` or identity): not required by NOT NULL on insert.
    pub generated: bool,
    /// `DEFAULT (expr)` SQL text.
    pub default: Option<Arc<str>>,
    /// `AS (expr) [STORED]` SQL text. Every such column is computed on write and kept in the row,
    /// STORED or not, as the emulator does: reads and indexes then see the value.
    pub expr: Option<Arc<str>>,
    /// `GENERATED BY DEFAULT AS IDENTITY`.
    pub identity: bool,
    /// `DEFAULT (PENDING_COMMIT_TIMESTAMP())`: storage writes the commit timestamp.
    pub default_commit_ts: bool,
    /// `ON UPDATE (PENDING_COMMIT_TIMESTAMP())`: updates that leave the column out set it to the
    /// commit timestamp.
    pub on_update_commit_ts: bool,
    /// An ENUM column's (or ENUM array's) defined numbers, sorted: writes of others fail.
    pub enum_numbers: Option<Arc<[i32]>>,
}

#[derive(Debug, Clone)]
pub struct CheckMeta {
    pub name: String,
    pub expr: Arc<str>,
}

#[derive(Debug, Clone)]
pub struct ChildRef {
    pub table: TableId,
    pub on_delete: OnDelete,
}

#[derive(Debug, Clone)]
pub struct TableMeta {
    pub name: String,
    pub columns: Vec<ColumnMeta>,
    by_name: HashMap<String, usize>,
    /// Column positions of the primary key, in key order.
    pub pk: Vec<usize>,
    pub pk_desc: Vec<bool>,
    /// `INTERLEAVE IN PARENT`: the parent row must exist.
    pub parent: Option<TableId>,
    pub children: Vec<ChildRef>,
    pub indexes: Vec<IndexId>,
    pub checks: Vec<CheckMeta>,
    /// Foreign keys declared on this table.
    pub fks_out: Vec<FkId>,
    /// Foreign keys referencing this table.
    pub fks_in: Vec<FkId>,
    /// Writes need more than copying values: defaults, generated or identity columns, checks.
    pub computed: bool,
    /// The generated (`AS (expr)`) columns in evaluation order: a column comes after every
    /// generated column its expression reads.
    pub generated_order: Vec<usize>,
    /// For each column, the non-generated columns its value depends on: itself for a plain
    /// column, and for a generated one every input column reached through its expression,
    /// transitively.
    pub inputs: Vec<Vec<usize>>,
}

impl TableMeta {
    pub fn column(&self, name: &str) -> Option<usize> {
        if let Some(&i) = self.by_name.get(name) {
            return Some(i);
        }
        self.by_name.get(&name.to_ascii_lowercase()).copied()
    }

    pub fn is_key_column(&self, col: usize) -> bool {
        self.pk.contains(&col)
    }

    pub fn key_types(&self) -> Vec<ColumnType> {
        self.pk
            .iter()
            .map(|&c| self.columns[c].ty.clone())
            .collect()
    }
}

/// Orders the generated columns so each comes after the generated columns it reads (declaration
/// order among independent ones), and resolves every column's non-generated inputs. DDL rejects
/// cycles; if one got through anyway, its columns keep declaration order.
fn generated_order(
    columns: &[ColumnMeta],
    by_name: &HashMap<String, usize>,
) -> (Vec<usize>, Vec<Vec<usize>>) {
    let reads: Vec<Vec<usize>> = columns
        .iter()
        .map(|cm| match &cm.expr {
            Some(e) => {
                let mut r: Vec<usize> = crate::expr::column_references(e)
                    .iter()
                    .filter_map(|w| by_name.get(w).copied())
                    .collect();
                r.sort_unstable();
                r.dedup();
                r
            }
            None => Vec::new(),
        })
        .collect();
    #[derive(Clone, Copy, PartialEq)]
    enum Mark {
        New,
        Visiting,
        Done,
    }
    fn visit(
        c: usize,
        columns: &[ColumnMeta],
        reads: &[Vec<usize>],
        mark: &mut [Mark],
        order: &mut Vec<usize>,
    ) {
        if mark[c] != Mark::New {
            return;
        }
        mark[c] = Mark::Visiting;
        for &d in &reads[c] {
            if columns[d].expr.is_some() {
                visit(d, columns, reads, mark, order);
            }
        }
        mark[c] = Mark::Done;
        order.push(c);
    }
    let mut mark = vec![Mark::New; columns.len()];
    let mut order = Vec::new();
    for (c, cm) in columns.iter().enumerate() {
        if cm.expr.is_some() {
            visit(c, columns, &reads, &mut mark, &mut order);
        }
    }
    let mut inputs: Vec<Vec<usize>> = (0..columns.len()).map(|c| vec![c]).collect();
    for &c in &order {
        let mut r: Vec<usize> = reads[c]
            .iter()
            .flat_map(|&d| inputs[d].iter().copied())
            .filter(|&d| d != c)
            .collect();
        r.sort_unstable();
        r.dedup();
        inputs[c] = r;
    }
    (order, inputs)
}

#[derive(Debug, Clone)]
pub struct IndexMeta {
    pub name: String,
    pub table: TableId,
    /// Table column positions of the index key.
    pub key: Vec<usize>,
    pub key_desc: Vec<bool>,
    pub unique: bool,
    pub null_filtered: bool,
    /// Nullable table columns whose NULL leaves a row out of the index: every key column of a
    /// NULL_FILTERED index, plus the columns of a filtered index's `WHERE c IS NOT NULL` clause.
    pub null_filter: Vec<usize>,
    /// Table column positions stored in each entry: index key, then STORING, then remaining PK columns.
    pub entry_columns: Vec<usize>,
    by_name: HashMap<String, usize>,
    /// A hidden index spanbolt maintains to check a foreign key; not readable by name.
    pub managed: bool,
}

pub type FkId = usize;

/// How to find rows of a table by the values of some of its columns.
#[derive(Debug, Clone)]
pub struct Lookup {
    pub target: Target,
    /// Column positions in the looked-up table, in lookup-key order.
    pub cols: Vec<usize>,
    pub desc: Vec<bool>,
    /// The columns are the whole primary key: an exact point lookup.
    pub point: bool,
    /// Positions in the *other* table of the foreign key that supply each lookup value.
    pub from_other: Vec<usize>,
}

/// An enforced foreign key.
#[derive(Debug, Clone)]
pub struct FkMeta {
    pub name: String,
    pub table: TableId,
    pub columns: Vec<usize>,
    pub ref_table: TableId,
    pub ref_columns: Vec<usize>,
    pub on_delete: OnDelete,
    /// Finds referenced rows from a referencing row.
    pub parent_lookup: Lookup,
    /// Finds referencing rows from a referenced row.
    pub child_lookup: Lookup,
}

impl IndexMeta {
    /// Position of a column within the index entry.
    pub fn column(&self, name: &str) -> Option<usize> {
        if let Some(&i) = self.by_name.get(name) {
            return Some(i);
        }
        self.by_name.get(&name.to_ascii_lowercase()).copied()
    }
}

#[derive(Debug, Clone, Default)]
pub struct Catalog {
    pub tables: Vec<TableMeta>,
    pub indexes: Vec<IndexMeta>,
    pub foreign_keys: Vec<FkMeta>,
    table_ids: HashMap<String, TableId>,
    index_ids: HashMap<String, IndexId>,
    managed_ids: HashMap<String, IndexId>,
}

/// The enum an ENUM or ENUM array column type names.
fn enum_name(ty: &ColumnType) -> Option<&str> {
    match ty {
        ColumnType::Enum(n) => Some(n),
        ColumnType::Array(e) => enum_name(e),
        _ => None,
    }
}

impl Catalog {
    pub fn table_id(&self, name: &str) -> Option<TableId> {
        if let Some(&i) = self.table_ids.get(name) {
            return Some(i);
        }
        self.table_ids.get(&name.to_ascii_lowercase()).copied()
    }

    pub fn index_id(&self, name: &str) -> Option<IndexId> {
        if let Some(&i) = self.index_ids.get(name) {
            return Some(i);
        }
        self.index_ids.get(&name.to_ascii_lowercase()).copied()
    }

    /// Any index, including managed ones, by exact name.
    pub(crate) fn index_id_any(&self, name: &str) -> Option<IndexId> {
        self.index_id(name)
            .or_else(|| self.managed_ids.get(name).copied())
    }

    pub fn table(&self, id: TableId) -> &TableMeta {
        &self.tables[id]
    }

    #[allow(clippy::should_implement_trait)]
    pub fn index(&self, id: IndexId) -> &IndexMeta {
        &self.indexes[id]
    }

    pub fn lookup_table(&self, name: &str) -> Result<TableId> {
        self.table_id(name)
            .ok_or_else(|| Error::not_found(format!("Table not found: {name}")))
    }

    pub fn build(schema: &Schema) -> Result<Catalog> {
        let mut cat = Catalog::default();
        for t in schema.tables.values() {
            let mut by_name = HashMap::with_capacity(t.columns.len() * 2);
            let columns: Vec<ColumnMeta> = t
                .columns
                .iter()
                .enumerate()
                .map(|(i, c)| {
                    by_name.insert(c.name.clone(), i);
                    by_name.insert(c.name.to_ascii_lowercase(), i);
                    let expr = c
                        .generated
                        .as_ref()
                        .and_then(Generated::expr)
                        .map(|(e, _)| Arc::from(e));
                    ColumnMeta {
                        name: c.name.clone(),
                        ty: c.ty.clone(),
                        not_null: c.not_null,
                        allow_commit_timestamp: c.allow_commit_timestamp,
                        max_len: match c.ty {
                            ColumnType::String(n) | ColumnType::Bytes(n) => n,
                            _ => None,
                        },
                        generated: c.generated.is_some(),
                        default: c.default.as_deref().map(Arc::from),
                        expr,
                        identity: matches!(c.generated, Some(Generated::Identity { .. })),
                        default_commit_ts: c
                            .default
                            .as_deref()
                            .is_some_and(spanbolt_ddl::is_pending_commit_timestamp),
                        on_update_commit_ts: c.on_update.is_some(),
                        enum_numbers: enum_name(&c.ty).and_then(|n| {
                            schema.proto_bundle.as_ref()?.enum_numbers.get(n).cloned()
                        }),
                    }
                })
                .collect();
            let mut pk = Vec::with_capacity(t.primary_key.len());
            let mut pk_desc = Vec::with_capacity(t.primary_key.len());
            for kp in &t.primary_key {
                let col = by_name
                    .get(&kp.column.to_ascii_lowercase())
                    .copied()
                    .ok_or_else(|| {
                        Error::failed_precondition(format!(
                            "Table {} references unknown key column {}",
                            t.name, kp.column
                        ))
                    })?;
                pk.push(col);
                pk_desc.push(kp.order == SortOrder::Desc);
            }
            let checks: Vec<CheckMeta> = t
                .checks
                .iter()
                .map(|c| CheckMeta {
                    name: c.name.clone(),
                    expr: Arc::from(c.expr.as_str()),
                })
                .collect();
            let computed = !checks.is_empty()
                || columns
                    .iter()
                    .any(|c| c.default.is_some() || c.expr.is_some() || c.identity);
            let (generated_order, inputs) = generated_order(&columns, &by_name);
            let id = cat.tables.len();
            cat.table_ids.insert(t.name.clone(), id);
            cat.table_ids.insert(t.name.to_ascii_lowercase(), id);
            cat.tables.push(TableMeta {
                name: t.name.clone(),
                columns,
                by_name,
                pk,
                pk_desc,
                parent: None,
                children: Vec::new(),
                indexes: Vec::new(),
                checks,
                fks_out: Vec::new(),
                fks_in: Vec::new(),
                computed,
                generated_order,
                inputs,
            });
        }
        for t in schema.tables.values() {
            let Some(il) = &t.interleave else { continue };
            let (Some(child), Some(parent)) = (cat.table_id(&t.name), cat.table_id(&il.parent))
            else {
                return Err(Error::failed_precondition(format!(
                    "Table {} is interleaved in unknown table {}",
                    t.name, il.parent
                )));
            };
            if il.in_parent {
                cat.tables[child].parent = Some(parent);
                cat.tables[parent].children.push(ChildRef {
                    table: child,
                    on_delete: il.on_delete.clone(),
                });
            }
        }
        for ix in schema.indexes.values() {
            let table = cat.table_id(&ix.table).ok_or_else(|| {
                Error::failed_precondition(format!(
                    "Index {} is on unknown table {}",
                    ix.name, ix.table
                ))
            })?;
            let tm = &cat.tables[table];
            let col = |n: &str| {
                tm.column(n).ok_or_else(|| {
                    Error::failed_precondition(format!(
                        "Index {} references unknown column {n}",
                        ix.name
                    ))
                })
            };
            let mut key = Vec::with_capacity(ix.key.len());
            let mut key_desc = Vec::with_capacity(ix.key.len());
            for kp in &ix.key {
                key.push(col(&kp.column)?);
                key_desc.push(kp.order == SortOrder::Desc);
            }
            let mut null_filter: Vec<usize> = Vec::new();
            if ix.null_filtered {
                null_filter.extend(&key);
            }
            if let Some(f) = &ix.filter {
                let cols = spanbolt_ddl::null_filter_columns(f)
                    .map_err(|e| Error::failed_precondition(format!("Index {}: {e}", ix.name)))?;
                for c in cols {
                    null_filter.push(col(&c)?);
                }
            }
            null_filter.retain(|&c| !tm.columns[c].not_null);
            null_filter.sort_unstable();
            null_filter.dedup();
            let mut entry_columns = key.clone();
            for s in &ix.storing {
                let c = col(s)?;
                if !entry_columns.contains(&c) {
                    entry_columns.push(c);
                }
            }
            for &c in &tm.pk {
                if !entry_columns.contains(&c) {
                    entry_columns.push(c);
                }
            }
            let mut by_name = HashMap::with_capacity(entry_columns.len() * 2);
            for (i, &c) in entry_columns.iter().enumerate() {
                by_name.insert(tm.columns[c].name.clone(), i);
                by_name.insert(tm.columns[c].name.to_ascii_lowercase(), i);
            }
            let id = cat.indexes.len();
            cat.index_ids.insert(ix.name.clone(), id);
            cat.index_ids.insert(ix.name.to_ascii_lowercase(), id);
            cat.indexes.push(IndexMeta {
                name: ix.name.clone(),
                table,
                key,
                key_desc,
                unique: ix.unique,
                null_filtered: ix.null_filtered,
                null_filter,
                entry_columns,
                by_name,
                managed: false,
            });
            cat.tables[table].indexes.push(id);
        }
        for t in schema.tables.values() {
            for fk in t.foreign_keys.iter().filter(|f| f.enforced) {
                cat.add_foreign_key(&t.name, fk)?;
            }
        }
        Ok(cat)
    }

    fn add_foreign_key(&mut self, table: &str, fk: &spanbolt_ddl::ForeignKey) -> Result<()> {
        let unknown = || {
            Error::failed_precondition(format!(
                "Foreign key {} references unknown tables or columns",
                fk.name
            ))
        };
        let t = self.table_id(table).ok_or_else(unknown)?;
        let rt = self.table_id(&fk.ref_table).ok_or_else(unknown)?;
        let cols = |tid: TableId, names: &[String]| -> Result<Vec<usize>> {
            names
                .iter()
                .map(|n| self.tables[tid].column(n).ok_or_else(unknown))
                .collect()
        };
        let columns = cols(t, &fk.columns)?;
        let ref_columns = cols(rt, &fk.ref_columns)?;
        let id = self.foreign_keys.len();
        let parent_lookup = self.lookup(rt, &ref_columns, &columns, &fk.name);
        let child_lookup = self.lookup(t, &columns, &ref_columns, &fk.name);
        self.foreign_keys.push(FkMeta {
            name: fk.name.clone(),
            table: t,
            columns,
            ref_table: rt,
            ref_columns,
            on_delete: fk.on_delete.clone(),
            parent_lookup,
            child_lookup,
        });
        self.tables[t].fks_out.push(id);
        self.tables[rt].fks_in.push(id);
        Ok(())
    }

    /// The cheapest way to find rows of `t` by the values of `cols`: its primary key, a prefix
    /// of it, an existing index, or a managed index created for the purpose. `other[i]` is the
    /// column of the other table that supplies the value of `cols[i]`.
    fn lookup(&mut self, t: TableId, cols: &[usize], other: &[usize], fk: &str) -> Lookup {
        let n = cols.len();
        let same_set = |key: &[usize]| key.len() >= n && cols.iter().all(|c| key[..n].contains(c));
        let make = |target: Target, key: &[usize], desc: &[bool], point: bool| Lookup {
            target,
            cols: key[..n].to_vec(),
            desc: desc[..n].to_vec(),
            point,
            from_other: key[..n]
                .iter()
                .map(|k| other[cols.iter().position(|c| c == k).unwrap_or(0)])
                .collect(),
        };
        let tm = &self.tables[t];
        if same_set(&tm.pk) {
            return make(Target::Table(t), &tm.pk, &tm.pk_desc, tm.pk.len() == n);
        }
        for &ix in &tm.indexes {
            let im = &self.indexes[ix];
            if same_set(&im.key) && im.null_filter.iter().all(|c| cols.contains(c)) {
                return make(Target::Index(ix), &im.key, &im.key_desc, false);
            }
        }
        let key = cols.to_vec();
        let mut entry_columns = key.clone();
        entry_columns.extend(tm.pk.iter().filter(|c| !key.contains(c)));
        let col_names: Vec<&str> = key.iter().map(|&c| tm.columns[c].name.as_str()).collect();
        let name = format!("IDX_{}_{}_{fk}", tm.name, col_names.join("_"));
        let id = self.indexes.len();
        self.managed_ids.insert(name.clone(), id);
        self.indexes.push(IndexMeta {
            name,
            table: t,
            key: key.clone(),
            key_desc: vec![false; n],
            unique: false,
            null_filtered: true,
            null_filter: key
                .iter()
                .copied()
                .filter(|&c| !tm.columns[c].not_null)
                .collect(),
            entry_columns,
            by_name: HashMap::new(),
            managed: true,
        });
        self.tables[t].indexes.push(id);
        make(Target::Index(id), &key, &vec![false; n], false)
    }
}

#[cfg(test)]
mod tests {
    use super::Catalog;
    use crate::testing::ddl;

    #[test]
    fn generated_columns_follow_their_inputs() {
        let cat = Catalog::build(&ddl(&[
            "CREATE TABLE T (K INT64 NOT NULL, A STRING(MAX) AS (CONCAT(B, '!')) STORED, \
             B STRING(MAX) AS (CONCAT(C, '?')), C STRING(MAX) AS (UPPER(X)) STORED, \
             X STRING(MAX), N INT64 AS (CHAR_LENGTH(A)), Y INT64) PRIMARY KEY (K)",
        ]))
        .unwrap_or_else(|e| panic!("{e}"));
        let tm = cat.table(cat.table_id("T").unwrap_or_default());
        let names = |cs: &[usize]| -> Vec<&str> {
            cs.iter().map(|&c| tm.columns[c].name.as_str()).collect()
        };
        assert_eq!(names(&tm.generated_order), ["C", "B", "A", "N"]);
        for g in ["A", "B", "C", "N"] {
            let c = tm.column(g).unwrap_or_default();
            assert_eq!(names(&tm.inputs[c]), ["X"], "{g}");
        }
        assert_eq!(names(&tm.inputs[tm.column("Y").unwrap_or_default()]), ["Y"]);
        assert!(tm.computed);
    }

    #[test]
    fn a_function_call_does_not_read_a_column_of_that_name() {
        // `UPPER(Name)` calls a function; it doesn't read the column `Upper`, which reads `A`.
        let cat = Catalog::build(&ddl(&[
            "CREATE TABLE T (K INT64 NOT NULL, Name STRING(MAX), \
             A STRING(MAX) AS (UPPER(Name)) STORED, \
             Upper STRING(MAX) AS (CONCAT(A, '!')) STORED) PRIMARY KEY (K)",
        ]))
        .unwrap_or_else(|e| panic!("{e}"));
        let tm = cat.table(cat.table_id("T").unwrap_or_default());
        let names = |cs: &[usize]| -> Vec<&str> {
            cs.iter().map(|&c| tm.columns[c].name.as_str()).collect()
        };
        assert_eq!(names(&tm.generated_order), ["A", "Upper"]);
        for g in ["A", "Upper"] {
            let c = tm.column(g).unwrap_or_default();
            assert_eq!(names(&tm.inputs[c]), ["Name"], "{g}");
        }
    }
}
