//! The seam through which the SQL engine evaluates schema expressions: DEFAULT values, generated
//! columns and CHECK constraints.

use std::sync::{Arc, RwLock};

use spanbolt_ddl::ColumnType;

use crate::catalog::TableMeta;
use crate::error::{Code, Error, Result};
use crate::state::WriteKind;
use crate::value::Value;

/// Evaluates a schema expression against one row.
pub trait ExprEvaluator: Send + Sync {
    /// Evaluates `expr` (GoogleSQL text as written in the DDL) with the columns of `table` bound
    /// to `row` (one value per column, in schema order), and coerces the result to `ty`
    /// (`BOOL` for CHECK constraints).
    fn eval(&self, expr: &str, table: &TableMeta, row: &[Value], ty: &ColumnType) -> Result<Value>;

    /// Checks a schema expression when DDL declares it (names resolve, the type fits). The error
    /// message is the one the DDL statement fails with.
    fn validate(&self, _expr: &str, _table: &TableMeta, _kind: &ExprKind) -> Result<()> {
        Ok(())
    }

    /// Checks the property graph `name` of `schema` when DDL creates or replaces it.
    fn validate_property_graph(
        &self,
        _schema: &Arc<spanbolt_ddl::Schema>,
        _name: &str,
    ) -> Result<()> {
        Ok(())
    }
}

/// Where a schema expression appears.
#[derive(Debug, Clone)]
pub enum ExprKind {
    Default { column: String, ty: ColumnType },
    Generated { column: String },
    Check { name: String },
}

static EVALUATOR: RwLock<Option<Arc<dyn ExprEvaluator>>> = RwLock::new(None);

/// Registers the process-wide evaluator (`None` unregisters it).
pub fn set_expr_evaluator(e: Option<Arc<dyn ExprEvaluator>>) {
    if let Ok(mut g) = EVALUATOR.write() {
        *g = e;
    }
}

pub fn expr_evaluator() -> Option<Arc<dyn ExprEvaluator>> {
    EVALUATOR.read().ok().and_then(|g| g.clone())
}

pub(crate) fn no_evaluator(what: &str) -> Error {
    Error::new(
        Code::Unimplemented,
        format!("{what} require the SQL engine"),
    )
}

pub(crate) const DEFAULTS: &str = "DEFAULT values";
pub(crate) const GENERATED: &str = "Generated columns";
pub(crate) const CHECKS: &str = "CHECK constraints on existing rows";

/// Fills the defaults of `missing` columns and recomputes the generated columns selected by
/// `regenerate`, in dependency order, then assigns identity values to missing identity columns.
pub fn compute_row(
    tm: &TableMeta,
    row: &mut [Value],
    missing: &dyn Fn(usize) -> bool,
    regenerate: &dyn Fn(usize) -> bool,
) -> Result<()> {
    let mut ev: Option<Arc<dyn ExprEvaluator>> = None;
    let mut get = |what: &str| -> Result<Arc<dyn ExprEvaluator>> {
        if ev.is_none() {
            ev = expr_evaluator();
        }
        ev.clone().ok_or_else(|| no_evaluator(what))
    };
    for (c, cm) in tm.columns.iter().enumerate() {
        if let Some(d) = &cm.default
            && missing(c)
        {
            row[c] = get(DEFAULTS)?.eval(d, tm, row, &cm.ty)?;
        }
    }
    for &c in &tm.generated_order {
        let cm = &tm.columns[c];
        if let Some(e) = &cm.expr
            && regenerate(c)
        {
            row[c] = get(GENERATED)?.eval(e, tm, row, &cm.ty)?;
        }
    }
    for (c, cm) in tm.columns.iter().enumerate() {
        if cm.identity && missing(c) && row[c].is_null() {
            row[c] = next_identity();
        }
    }
    Ok(())
}

/// Values for `GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE)` columns: a process-wide
/// counter with its 63 low bits reversed, so values are unique, positive and spread out.
fn next_identity() -> Value {
    use std::sync::atomic::{AtomicU64, Ordering};
    static NEXT: AtomicU64 = AtomicU64::new(1);
    let n = NEXT.fetch_add(1, Ordering::Relaxed);
    Value::Int64((n.reverse_bits() >> 1) as i64)
}

/// The identifiers `expr` refers to, lowercased. String and bytes literals don't count; when
/// `expr` does not tokenize, every identifier-shaped word does (a conservative over-approximation).
pub fn identifiers(expr: &str) -> Vec<String> {
    match spanbolt_ddl::identifiers(expr) {
        Some(ids) => ids.into_iter().map(|w| w.to_ascii_lowercase()).collect(),
        None => expr
            .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .filter(|w| !w.is_empty())
            .map(str::to_ascii_lowercase)
            .collect(),
    }
}

/// Whether `expr` refers to the identifier `name` (case-insensitive; see [`identifiers`]).
pub fn mentions(expr: &str, name: &str) -> bool {
    identifiers(expr)
        .iter()
        .any(|w| w.eq_ignore_ascii_case(name))
}

/// Rejects a write that leaves a generated primary-key column without its inputs, as the emulator
/// does: every column the key's expression reads must be written, or (except in an Update, which
/// may write the key itself instead) have a DEFAULT. A key that reads another generated column can
/// therefore not be inserted at all.
pub fn check_generated_key_inputs(
    tm: &TableMeta,
    kind: WriteKind,
    columns: &[usize],
) -> Result<()> {
    for &k in &tm.pk {
        let km = &tm.columns[k];
        let Some(e) = km.expr.as_deref() else {
            continue;
        };
        if kind == WriteKind::Update && columns.contains(&k) {
            continue;
        }
        let ids = identifiers(e);
        let unset = tm.columns.iter().enumerate().any(|(c, cm)| {
            ids.iter().any(|w| w.eq_ignore_ascii_case(&cm.name))
                && !columns.contains(&c)
                && (kind == WriteKind::Update || (cm.default.is_none() && !cm.identity))
        });
        if unset {
            return Err(Error::failed_precondition(if kind == WriteKind::Update {
                format!(
                    "The value of generated primary key column `{}.{}` must be explicitly specified or else its non-key dependent columns must be specified in Update mutations.",
                    tm.name, km.name
                )
            } else {
                format!(
                    "The value of generated primary key column `{}.{}` cannot be evaluated since value of all its dependent columns is not specified.",
                    tm.name, km.name
                )
            }));
        }
    }
    Ok(())
}

/// Evaluates the table's CHECK constraints when an evaluator is registered; without one they are
/// not enforced.
pub(crate) fn check_row(
    tm: &TableMeta,
    row: &[Value],
    key_debug: &dyn Fn() -> String,
) -> Result<()> {
    if tm.checks.is_empty() {
        return Ok(());
    }
    let Some(ev) = expr_evaluator() else {
        return Ok(());
    };
    for ck in &tm.checks {
        if ev.eval(&ck.expr, tm, row, &ColumnType::Bool)? == Value::Bool(false) {
            return Err(Error::constraint(
                Code::OutOfRange,
                format!(
                    "Check constraint `{}`.`{}` is violated for key {}",
                    tm.name,
                    ck.name,
                    key_debug()
                ),
            ));
        }
    }
    Ok(())
}
