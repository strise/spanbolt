#!/usr/bin/env python3
"""Writes a trimmed copy of ICU's prebuilt common data as a C array.

    icu_data.py <icudtNNl.dat> <out.c> [--list]

ICU's static data library holds the whole icudtNNl.dat (32 MB in ICU 76): every locale's names,
currencies, units, collation tailorings and break dictionaries, and the codepage converters. The
GoogleSQL analyser only needs the locale-independent pieces (normalisation, properties, the root
collation and the supplemental tables), and spanbolt evaluates every function in Rust. This keeps
those and drops the rest.

The output defines the entry point `icudtNN_dat`. It is compiled into //:shim, which the linker sees
before ICU's archives, so libicudata.a's member (the full data) is never pulled in. The format
("CmnD", common data) is a header, a table of contents of (name offset, data offset) pairs sorted by
name, the names, and the items, each 16-byte aligned. See ICU's source/common/ucmndata.h.
"""

import re
import struct
import sys

# A locale's own file: `de.res`, `en_GB.res`, `sr_Latn_BA.res`, `ars.res`.
LOCALE = re.compile(r"^[a-z]{2,3}(_[A-Za-z0-9]+)*\.res$")
# Every tree's index and shared files, kept even where LOCALE matches them.
SHARED = ("root.res", "res_index.res", "pool.res")


def keep(name: str) -> bool:
    path = name.split("/", 1)[1]  # drop the "icudt76l/" prefix
    parts = path.split("/")
    base = parts[-1]
    if base.endswith(".cnv"):  # codepage converters (cnvalias.icu stays)
        return False
    if len(parts) == 1:
        return not LOCALE.match(base) or base in SHARED
    tree = parts[0]
    if tree == "translit":  # transliterators (1 MB of rules in root.res alone)
        return False
    if tree == "rbnf":
        return base in SHARED
    if tree == "brkitr" and base.endswith(".dict"):
        return False
    if tree == "coll":
        return base in SHARED or base == "ucadata.icu"
    return not LOCALE.match(base) or base in SHARED


def trim(data: bytes):
    header_size, magic1, magic2 = struct.unpack_from("<HBB", data, 0)
    if (magic1, magic2) != (0xDA, 0x27) or data[12:16] != b"CmnD" or data[8] != 0:
        raise SystemExit("not little-endian ICU common data")
    toc = header_size
    (count,) = struct.unpack_from("<I", data, toc)
    entries = [struct.unpack_from("<II", data, toc + 4 + 8 * i) for i in range(count)]
    starts = sorted(d for _, d in entries) + [len(data) - toc]
    end_of = {s: starts[i + 1] for i, s in enumerate(starts[:-1])}
    items = []
    for name_off, data_off in entries:
        name = data[toc + name_off : data.index(b"\0", toc + name_off)].decode()
        if keep(name):
            items.append((name, data[toc + data_off : toc + end_of[data_off]]))

    def align(n: int) -> int:
        return (n + 15) & ~15

    names_at = 4 + 8 * len(items)
    names = b""
    name_offs = []
    for name, _ in items:
        name_offs.append(names_at + len(names))
        names += name.encode() + b"\0"
    body = b""
    data_offs = []
    first = align(names_at + len(names) + toc) - toc
    for _, blob in items:
        data_offs.append(first + len(body))
        body += blob + b"\0" * (align(len(blob)) - len(blob))
    out = bytearray(data[:toc])
    out += struct.pack("<I", len(items))
    for n, d in zip(name_offs, data_offs):
        out += struct.pack("<II", n, d)
    out += names
    out += b"\0" * (toc + first - len(out))
    out += body
    return bytes(out), [n for n, _ in items]


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, "rb").read()
    m = re.search(r"icudt(\d+)l\.dat$", src)
    if not m:
        raise SystemExit(f"unexpected data file name {src}")
    out, names = trim(data)
    if "--list" in sys.argv:
        print("\n".join(names))
    symbol = f"icudt{m.group(1)}_dat"
    with open(dst, "w") as f:
        f.write(f"/* Generated by tools/icu_data.py from {src.rsplit('/', 1)[-1]}: */\n")
        f.write(f"/* {len(names)} items, {len(out)} of {len(data)} bytes. */\n")
        f.write(f"__attribute__((aligned(16), used)) const unsigned char {symbol}[{len(out)}] =\n")
        for i in range(0, len(out), 4096):
            chunk = out[i : i + 4096]
            f.write('"' + "".join(f"\\x{b:02x}" for b in chunk) + '"\n')
        f.write(";\n")


if __name__ == "__main__":
    main()
