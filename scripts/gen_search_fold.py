#!/usr/bin/env python3
"""Prints the tables in crates/sql/src/search/fold.rs from Python's Unicode data.

    python3 scripts/gen_search_fold.py
"""
import unicodedata as u

print(f"// Generated by scripts/gen_search_fold.py from Unicode {u.unidata_version}.")
print()
print("/// Letters (not superscript or subscript ones) and decimal digits with a compatibility form,")
print("/// which Cloud Spanner uses.")
print("const COMPAT: &[(char, char)] = &[")
ranges = []
for i in range(0x80, 0x110000):
    ch = chr(i)
    d = u.decomposition(ch)
    cat = u.category(ch)
    if (
        d.startswith("<")
        and (cat[0] == "L" or cat == "Nd")
        and d.split(">")[0][1:] not in ("super", "sub")
    ):
        if ranges and ranges[-1][1] == i - 1:
            ranges[-1][1] = i
        else:
            ranges.append([i, i])
for a, b in ranges:
    print(f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}'),")
print("];")
print()
print("/// Full case folding where it differs from `char::to_lowercase`, but for Cherokee, `ß`, `ẞ`")
print("/// and `İ` (`fold_char`).")
print("const FOLD: &[(char, &str)] = &[")
for i in range(0x110000):
    ch = chr(i)
    if ch in "ßẞİ" or 0x13A0 <= i <= 0x13FD or 0xAB70 <= i <= 0xABBF or u.category(ch) == "Cs":
        continue
    if ch.casefold() != ch.lower():
        f = "".join(f"\\u{{{ord(c):x}}}" for c in ch.casefold())
        print(f"    ('\\u{{{i:x}}}', \"{f}\"),")
print("];")
