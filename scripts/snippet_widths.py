#!/usr/bin/env python3
"""Generates crates/sql/src/search/snippet_widths.rs: the widths SNIPPET's max_snippet_width counts
for characters above U+00FF, in fifths of an average character.

Cloud Spanner measures a snippet in Arial's advance widths: a character costs its advance times 12
over the em, rounded half down (`x` 0.5 em is 6, `m` 10, `ъ` 7.5 is 7). That holds for the WGL4
characters Arial has always had, Hebrew, Arabic and Vietnamese letters (snippet_widths.case);
other Latin, Greek and Cyrillic letters measure 9.

Usage: python3 -I scripts/snippet_widths.py [path/to/Arial.ttf] > crates/sql/src/search/snippet_widths.rs
Needs fontTools (`pip install fonttools`); the default font path is macOS's Arial.
"""

import sys
from fractions import Fraction

from fontTools.ttLib import TTFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Supplemental/Arial.ttf"

# WGL4 above Latin-1 (letters and text punctuation; arrows, maths and box drawing left out), then
# Hebrew and Arabic letters and Vietnamese.
RANGES = [
    (0x0100, 0x017F), (0x0192, 0x0192), (0x01FA, 0x01FF), (0x02C6, 0x02C7), (0x02C9, 0x02C9),
    (0x02D8, 0x02DD), (0x0384, 0x038A), (0x038C, 0x038C), (0x038E, 0x03A1), (0x03A3, 0x03CE),
    (0x0401, 0x040C), (0x040E, 0x044F), (0x0451, 0x045C), (0x045E, 0x045F), (0x0490, 0x0491),
    (0x05D0, 0x05EA), (0x0621, 0x063A), (0x0640, 0x064A), (0x1E80, 0x1E85), (0x1EA0, 0x1EF9),
    (0x2013, 0x2015), (0x2017, 0x201E), (0x2020, 0x2022), (0x2026, 0x2026), (0x2030, 0x2030),
    (0x2032, 0x2033), (0x2039, 0x203A), (0x203C, 0x203C), (0x203E, 0x203E), (0x2044, 0x2044),
    (0x20AC, 0x20AC), (0x2122, 0x2122),
]


def main():
    font = TTFont(FONT)
    cmap = font.getBestCmap()
    advances = font["hmtx"].metrics
    em = font["head"].unitsPerEm
    rows = []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            if cp not in cmap:
                continue
            x = Fraction(advances[cmap[cp]][0] * 12, em)
            width = -((-(2 * x - 1)) // 2)  # ceil(x - 1/2): halves round down
            if rows and rows[-1][1] == cp - 1 and rows[-1][2] == width:
                rows[-1][1] = cp
            else:
                rows.append([cp, cp, width])
    out = sys.stdout
    out.write("// Generated by scripts/snippet_widths.py from Arial's advance widths. Do not edit.\n\n")
    out.write("/// `(first, last, width)`: characters above U+00FF whose SNIPPET width is Arial's, sorted.\n")
    out.write("pub const ARIAL: &[(u32, u32, u8)] = &[\n")
    for lo, hi, w in rows:
        out.write(f"    (0x{lo:04X}, 0x{hi:04X}, {w}),\n")
    out.write("];\n")


main()
